# files without #FID columns that generated with the vcf files as input.


import argparse
import datetime

version = "2.0.0"

# Set arguments
parser = argparse.ArgumentParser(
    prog="Choose Preferred Samples between Kinship Relevant Samples",
    description=(
        "This script is used to choose the preferred samples between kinship "
        "relevant (kinship>=0.354) samples. This script depends on the Plink2 "
        'Kinship result, and will generate the two output files named '
        '"<kinship_prefix>.king.cutoff.substitute.in.id" and '
        '"<kinship_prefix>.king.cutoff.substitute.out.id".')
)
parser.add_argument('-p','--prefer_list', required=True,
    help=(
        "The list of preferred samples, one sample per line. The samples in "
        "this list will be chosen as the preferred samples.")
)
parser.add_argument('-k','--kinship_prefix', required=True,
    help=('The prefix of the Plink2 Kinship result. The Plink2 Kinship result '
          'files, including the "*.kin0","*.king.cutoff.in.id" and '
          '"*.king.cutoff.out.id" are expected to be in the same directory.')
)
args=parser.parse_args()

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


prefer_list = args.prefer_list

AKP = args.kinship_prefix
in_list = AKP + '.king.cutoff.in.id'
out_list = AKP + '.king.cutoff.out.id'
kinship = AKP + '.kin0'
substitute_in_list = AKP + '.king.cutoff.substitute.in.id'
substitute_out_list = AKP + '.king.cutoff.substitute.out.id'


# Read in files
with open(prefer_list, 'r', encoding='utf-8') as f:
    prefer_list = f.read().strip().split('\n')
    print(f'Number of preferred samples: {len(prefer_list)}')

def read_in_out_list(file):
    """function to read in_list or out_list files generated by Plink2"""
    with open(file,'r') as f:
        f_split = f.read().strip().split('\n')
        if not f_split[0].endswith('IID'):
            raise ValueError(
                f'The first line of the following <in_list> or <out_list> file'
                f'should contain "IID": \n\t{file}')
        f_split = f_split[1:]
        # The in_list file may contains one or two columns.
        # Previous script generate the file contains the FID using bed file
        # as input file.
        f_split = [i.split('\t')[1]
                   if len(i.split('\t')) == 2 else i
                   for i in f_split]
        print(f'Number of samples in {".".join(file.split(".")[-4:])}: '
              f'{len(f_split)}')
        return f_split

in_list = read_in_out_list(in_list)
out_list = read_in_out_list(out_list)

with open(kinship,'r') as f:
    f_split = f.read().strip().split('\n')
    if not f_split[0].endswith('KINSHIP'):
        raise ValueError(
            f'The first line of the {kinship} file should contain the header '
            '"KINSHIP"')
    dic_kinship = {}
    f = f_split[1:]
    for line in f:
        line = line.split('\t')
        if len(line) == 8:
            ind1 = line[1]
            ind2 = line[3]
        elif len(line) == 6:
            ind1 = line[0]
            ind2 = line[1]
        else:
            raise ValueError(
                f'Unexpected number of columns in the {kinship} file')

        kin = float(line[-1])

        if kin >= 0.354:
            for i in range(2):
                ind = [ind1,ind2][i]
                if ind in prefer_list:
                    dic_kinship[ind] = dic_kinship.get(ind,[])
                    dic_kinship[ind].append([ind1,ind2][1-i])
print(f'Number of preferred kinship relevant samples: {len(dic_kinship)}')

# Substitute the samples in out_list with the samples in prefer_list
no_substitution = []
first_substitute = True
for i,ind in enumerate(out_list):
    if ind in prefer_list:
        substitute = False
        for s in dic_kinship[ind]:
            if s not in out_list and s not in prefer_list:
                if first_substitute:
                    print("\nFollowing samples are substituted with preferred "
                          "samples:")

                print('\t', s , "\t->\t", ind, sep='')
                in_list[in_list.index(s)] = ind
                out_list[i] = s
                substitute = True
                first_substitute = False
                break

        if not substitute:
            no_substitution.append(ind)

if len(no_substitution) > 0:
    print(
        f'\nNo substitution for the {len(no_substitution)} preferred samples:',
        f'\n\t'.join(no_substitution),sep='\n\t')


# Write the substituted in_list and out_list
with open(substitute_in_list,'w') as f:
    f.write('\n'.join(in_list))

with open(substitute_out_list,'w') as f:
    f.write('\n'.join(out_list))



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
