#   The script will substitute the samples according to the SNP missing
#   number instead of the preferred samples list. The missing number is
#   calculated by bcftools.


import argparse
import textwrap
import datetime


def wrap(text, width=79):
    """Wraps the given text to the specified width."""
    return textwrap.fill(text, width=width, subsequent_indent=' ' * 4)


# Set arguments
parser = argparse.ArgumentParser(
    prog="Choose Preferred Samples between Kinship Relevant Samples",
    description=wrap(
        'This script serves the purpose of substituting samples with '
        'kinship values equal to or greater than 0.354 in the plink2 '
        'kinship results. This substitution is based on the SNP missing '
        'number statistics obtained through bcftools. Upon execution, the '
        'script will produce two output files named '
        '"<kinship_prefix>.king.cutoff.substitute_using_SNP_missing.in.id" '
        'and '
        '"<kinship_prefix>.king.cutoff.substitute_using_SNP_missing.out.id".'
    )
)
parser.add_argument(
    '-s',
    '--bcftools_stats',
    required=True,
    help=(
        'The bcftools stats result file. This file should have "PSC" filed. '
        'To generated the "PSC" filed in the stats file, use the parameter '
        '"-s -" when running bcftools stats.'
    )
)
parser.add_argument(
    '-k',
    '--kinship_prefix',
    required=True,
    help=(
        'The prefix of the Plink2 Kinship result. The Plink2 Kinship result '
        'files, including the "*.kin0","*.king.cutoff.in.id" and '
        '"*.king.cutoff.out.id" are expected to be in the same directory.'
    )
)
args = parser.parse_args()

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

bcftools_stats = args.bcftools_stats

AKP = args.kinship_prefix
in_list = AKP + '.king.cutoff.in.id'
out_list = AKP + '.king.cutoff.out.id'
kin0 = AKP + '.kin0'
substitute_in_list = AKP + '.king.cutoff.substitute_using_SNP_missing.in.id'
substitute_out_list = AKP + '.king.cutoff.substitute_using_SNP_missing.out.id'

# Read bcftools stats files
missing_number = {}
with open(bcftools_stats, 'r', encoding='utf-8') as file:
    lines = file.readlines()
    for line in lines:
        if line.strip().startswith('PSC'):
            columns = line.strip().split('\t')
            sample_id, missing = columns[2], columns[13]
            missing_number[sample_id] = int(missing)
            if len(missing_number) == 0:
                raise ValueError(
                    f'No "PSC" filed found in the {bcftools_stats} file.'
                )

# Read plink in_list and out_list files
def read_in_out_list(file):
    """function to read in_list or out_list files generated by Plink2"""
    with open(file, 'r', encoding='utf-8') as fo:
        f_split = fo.read().strip().split('\n')
        if not f_split[0].endswith('IID'):
            raise ValueError(
                f'The first line of the following <in_list> or <out_list> file'
                f' should contain "IID": \n\t{file}')
        f_split = f_split[1:]
        # The in_list file may contains one or two columns.
        # Previous script generate the file contains the FID using bed file
        # as input file.
        f_split = [i.split('\t')[1]
                   if len(i.split('\t')) == 2 else i
                   for i in f_split]
        print(f'Number of samples in {".".join(file.split(".")[-4:])}: '
              f'{len(f_split)}')
        return f_split

in_list = read_in_out_list(in_list)
out_list = read_in_out_list(out_list)

# Read plink kin0 file
with open(kin0, 'r', encoding='utf-8') as file:
    f_split = file.read().strip().split('\n')
    if not f_split[0].endswith('KINSHIP'):
        raise ValueError(
            f'The first line of the {kin0} file should contain the header '
            '"KINSHIP"'
        )
    dic_kinship = {}
    f_split = f_split[1:]
    for line in f_split:
        line = line.split('\t')
        if len(line) == 8:
            ind1 = line[1]
            ind2 = line[3]
        elif len(line) == 6:
            ind1 = line[0]
            ind2 = line[1]
        else:
            raise ValueError(
                f'Unexpected number of columns in the {kin0} file'
            )

        kin = float(line[-1])

        if kin >= 0.354:
            for i in range(2):
                ind = [ind1, ind2][i]
                dic_kinship[ind] = dic_kinship.get(ind, [])
                dic_kinship[ind].append([ind1, ind2][1 - i])
print(f'Number of kinship relevant samples: {len(dic_kinship)}')

# Substitute the samples in out_list with the samples in in_list
first_substitute = True
for i, ind in enumerate(out_list):
    for s in dic_kinship[ind]:
        if s in in_list:
            missing_s = missing_number[s]
            missing_ind = missing_number[ind]
            if missing_ind < missing_s:
                if ind in out_list:
                    if first_substitute:
                        print(wrap("\nFollowing samples are substituted with "
                                   "lower SNP missing samples:"))
                        first_substitute = False

                    print('\t', s, "->", ind, sep='\t')
                    in_list[in_list.index(s)] = ind
                    out_list[i] = s
        elif s not in out_list:
            raise ValueError(
                f'Unexpected sample {s} in the {kin0} file. '
                f'Please check the {kin0} file.')

# Write the substituted in_list and out_list
with open(substitute_in_list, 'w', encoding='utf-8') as f:
    f.write('\n'.join(in_list)+ '\n')

with open(substitute_out_list, 'w', encoding='utf-8') as f:
    f.write('\n'.join(out_list)+ '\n')

end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time - start_time).center(79))
