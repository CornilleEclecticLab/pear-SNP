import datetime
import sys
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)




# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)


# Read chromosome list
chromosomes = []
with open(os.path.join(input_dir, 's01.chr_list.txt'), 'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            chromosomes.append(line)


# Generate script for each chromosome
for chr in chromosomes:
    vcf = os.path.join(input_dir, f's01.input_vcf.gz')
    choosing_list = os.path.join(input_dir, f's01.choosing_list.txt')
    rename_list = os.path.join(input_dir, f's01.rename_list.txt')
    vcf_choosing = os.path.join(output_dir, f'{chr}.choosing.vcf.gz')
    with open(os.path.join(sub_script_dir, f'{script_basename}.{chr}.sh'), 'w') as fh:
        fh.write(f'''\
#!/bin/bash
# This script was automatically generated by {script_basename} v{version}
#SBATCH -J {script_basename}.{chr}
#SBATCH -o {script_basename}.{chr}.%J.out
#SBATCH -e {script_basename}.{chr}.%J.err
#SBATCH -c 4

module load bcftools/1.14

bcftools view \\
    -S {choosing_list} \\
    {vcf} \\
    -r {chr} \\
| bcftools reheader \\
    -s {rename_list} \\
| bcftools view \\
    -O z4 \\
    -o {vcf_choosing}

tabix -p vcf {vcf_choosing}
''')


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))