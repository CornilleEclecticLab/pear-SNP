import datetime
import sys
import textwrap
import os
import glob
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output')
sub_output_dir_father = os.path.join(output_dir,script_basename)
sub_script_dir_father = os.path.join(bin_dir,script_basename)

os.makedirs(sub_output_dir_father, exist_ok=True)
os.makedirs(sub_script_dir_father, exist_ok=True)

header = f"""#!/usr/bin/env bash
# This script was generated by ../../{script_basename}.py
# at {start_time}
# v{version}
"""

# Glob fasta files
s01_dir = os.path.join(output_dir, 's01.prepare_fasta_gff')
fastas = glob.glob(os.path.join(s01_dir, '*.chr_list.fasta'))

print(f'Found {len(fastas)} fasta files:')

for fa in fastas:
    print('Processing:', fa)
    basename = os.path.basename(fa)
    prefix = os.path.splitext(basename)[0]
    gff_file = os.path.join(s01_dir, prefix+'.gff')
    
    prefix = prefix.replace('.chr_list','')
    sub_output_dir = os.path.join(sub_output_dir_father, prefix)
    sub_script_dir = os.path.join(sub_script_dir_father, prefix)
    
    # Ensure output directory exists
    os.makedirs(sub_output_dir, exist_ok=True)
    os.makedirs(sub_script_dir, exist_ok=True)
       
    with open(os.path.join(sub_script_dir, script_basename+".sh"), 'w') as fo:
        fo.write(header)
        fo.write(f"""
#SBATCH -J {script_basename}.sh
#SBATCH -o {script_basename}.%J.out
#SBATCH -e {script_basename}.%J.err
#SBATCH -c 2
#SBATCH --mem=16G
#SBATCH -p long

source {os.path.join(bin_dir,'s00.load_software.sh')}

centIER.py \\
    --gff {gff_file} \\
    -o {sub_output_dir} \\
    {fa}
""")
    while True:
        inputs = input("Do you want to submit the generated script to the cluster for running? [y/n]")
        if inputs.lower() == 'y':
            os.system(f'cd {sub_script_dir} && sbatch {script_basename}.sh')
            print("This script has been submitted to the cluster.")
            break
        elif inputs.lower() == 'n':
            print("Submission cancelled.")
            break
        else:
            print("Invalid input. Please enter 'y' or 'n'.")
    


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
