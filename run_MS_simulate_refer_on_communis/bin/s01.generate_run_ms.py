import datetime
import sys
import textwrap
import os
import random
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)


# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Read populations
populations = {}
with open(os.path.join(
    input_dir, 's01.sample_tab_population.txt'), 'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#') or line == '':
            continue
        else:
            ind, pop = line.split()[0:2]
            populations[pop] = populations.get(pop, [])
            populations[pop].append(ind)


# Load par files
pars = {}
for pop in populations:
    par_file = os.path.join(input_dir, 'par_files',f'{pop}.REP1.par')
    try:
        file = open(par_file, 'r')
    except FileNotFoundError:
        raise FileNotFoundError(f"Cannot find par file: {par_file}")

    par = file.read().strip()
    if par == '':
        raise ValueError(f"Empty par file: {par_file}")
    pars[pop] = par
    


# Header for the sub-script
header = f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""

for repeat in range(1, 11): # 1-10
    seed0, seed1, seed2 = [random.randint(1, 1000000) for _ in range(3)]
    for pop in populations:
        par = pars[pop]
        sub_script_base = script_basename + f'.{pop}.REP{repeat}'
        output_file_base = os.path.join(output_dir, f"ms.{pop}.REP{repeat}")
        with open(os.path.join(sub_script_dir, sub_script_base+'.sh'), 'w') as fo:
            fo.write(header)
            fo.write(f"""
#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH -c 1
#SBATCH --mem=2G

source {bin_dir}/s00.load_ms.sh

ms  {len(populations[pop])*2} \\
    100 \\
    -seeds {seed0} {seed1} {seed2} \\
    {par} \\
> {output_file_base}.txt

perl {os.path.join(bin_dir, 'ms_modify.pl')} \\
     {output_file_base}.txt \\
> {output_file_base}.modified.txt

""")


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))