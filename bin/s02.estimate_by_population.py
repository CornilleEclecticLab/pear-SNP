import datetime
import os
import sys
import textwrap
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

# The type of spline to use for the analysis, "piecewise","cubic", or "pchip"
# The default value in recent versions is piecewise to better match the output from {P,M}SMC. To enable cubic splines (what is used in the paper), use --spline cubic or --spline pchip. (For details on the differences between cubic and pchip splines see https://blogs.mathworks.com/cleve/2012/07/16/splines-and-pchips/#98ccb1df-b614-41d4-b1b5-e090a87e0d46.)
spline_type = ("piecewise","cubic","pchip")[1]  # piecewise, cubic, pchip

version = "2.0.0"
cpu_cores = '20'
script_basename = "s02.estimate_by_population_"+spline_type
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
input_dir = work_dir+'/input/'
output_s01_dir = work_dir+'/output/s01.vcf2smc_by_chr'
output_dir = work_dir+'/output/'+script_basename
sub_script_dir = work_dir+'/bin/'+script_basename




vcf = input_dir+"/s01.input.vcf.gz"
chromosome_list = input_dir+"/s01.scaffolds_list.txt"
individual_population_list = input_dir+"/s01.individuals_and_populations_list.txt"  # Format: individual_name population_name
load_singularity = '# module load system/singularity-3.7.3 # singularity is installed and callable on the cluster without loading a module'
mutation_rate = '3.9e-8'   # The mutation rate of the species per generation

os.system("mkdir -p "+sub_script_dir)
os.system("mkdir -p "+output_dir)




with open(chromosome_list,'r') as fr:
    chr_list = fr.read().strip().split('\n')
    info=f'Reading the "chromosomes list": {",".join(chr_list)}'
    print(textwrap.fill(info, width=79, subsequent_indent=' '*4))



population_dict = {}
with open(individual_population_list,'r') as fr:
    for line in fr:
        if line.startswith("#") or line.strip()=='':
            continue 
        line = line.strip().split()
        individual = line[0]
        population = line[1]
        info=f'Reading the "individuals_and_populations_list": {individual} {population}'
        print(textwrap.fill(info, width=79, subsequent_indent=' '*4))

        population_dict[population] = population_dict.get(population,list())
        population_dict[population].append(individual)



for pop, inds in population_dict.items(): 
        sub_script_basename = f"estimate.{pop}"
        sub_script = f"{sub_script_dir}/{sub_script_basename}.sh"
        smc_list = ' \\\n        '.join([f"{output_s01_dir}/{pop}.{chr}.smc.gz" for chr in chr_list])

        with open(sub_script,"w") as fo:
            content = f'''#!/usr/bin/env bash

# This sub-script was generated by {script_basename}.py V{version} at {start_time}


#SBATCH -J {sub_script_basename}
#SBATCH -o {sub_script_basename}.%J.out
#SBATCH -e {sub_script_basename}.%J.err
#SBATCH --cpus-per-task {cpu_cores}


{load_singularity}


singularity run -B  {work_dir}:{work_dir} \\
    {work_dir}/bin/smcpp.sif estimate \\
        --cores {cpu_cores} \\
        --timepoints 100 1e5 \\
        --outdir {output_dir}/{pop}/ \\
        --spline {spline_type} \\
        --polarization-error 0.5 \\
        {mutation_rate} \\
        {smc_list}
'''
            fo.write(content)



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
