import datetime
import os
import sys
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

version = "1.0.0"
script_basename = "s01.vcf2smc_by_chr"
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
input_dir = work_dir+'/input/'
output_dir = work_dir+'/output/'+script_basename
sub_script_dir = work_dir+'/bin/'+script_basename



vcf = input_dir+"/s01.input.vcf.gz"
chromosome_list = "input/s01.scaffolds_list.txt"  # Format: individual_name population_name
load_singularity = 'module load system/singularity-3.7.3'



os.system("mkdir -p "+sub_script_dir)
os.system("mkdir -p "+output_dir)



with open(work_dir+'/'+chromosome_list,'r') as fr:
    chr_list = fr.read().strip().split('\n')
    print(chr_list)



population_dict = {}
with open(input_dir+"/s01.individuals_and_populations_list.txt",'r') as fr:
    for line in fr:
        if line.startswith("#") or line.strip()=='':
            continue 
        line = line.strip().split()
        individual = line[0]
        population = line[1]
        print(individual,population)

        population_dict[population] = population_dict.get(population,list())
        population_dict[population].append(individual)



for pop, inds in population_dict.items(): 
    for chr in chr_list:
        sub_script = sub_script_dir+"/vcf2smc.{pop}.{chr}.sh".format(pop=pop,chr=chr)
        out = output_dir+'/'+pop+'.'+chr+'.smc.gz'
        inds = ",".join(inds)

        with open(sub_script,"w") as fo:
            content = '''#!/usr/bin/env bash

# This sub-script was generated by {script_basename}.py V{version} at {time}


#SBATCH -J {sub_script}
#SBATCH -o {sub_script}.%J.out
#SBATCH -e {sub_script}.%J.err


{load_singularity}


singularity run -B  {work_dir}:{work_dir} \\
    {work_dir}/bin/smcpp.sif vcf2smc \\
        {vcf} \\
        {out} \\
        {chr} \\
        {pop}:{inds} 
'''.format(
    script_basename=script_basename,
    version=version, 
    time=start_time, 
    sub_script=sub_script,
    load_singularity=load_singularity, 
    work_dir=work_dir, 
    vcf=vcf,
    out=out, 
    chr=chr, 
    pop=pop, 
    inds=inds)
            fo.write(content)



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
