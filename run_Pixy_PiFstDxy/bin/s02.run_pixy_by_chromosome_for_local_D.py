import datetime
import sys
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.2.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

########################################################################
# Set input files
########################################################################
chr_vcf_list = os.path.join(input_dir,'s02.concat_chr_vcf_list.txt')
chr_list = os.path.join(input_dir,f's01.chromosome_list.txt')
pop_path = os.path.join(input_dir,'s02.sample_tab_population.txt')
# Dinvestigate windows exported by s08.x1.enrichment_pi_matched.R --export_windows_only
local_D_bed = '/shared/projects/pear_snp3/pear/run_Dsuite_genome_masked/output/s08.x1.enrichment_pi_matched/Oriental.aggregate.dinv_windows.pixy_regions.1based.bed'

# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Read chromosome ID as a list
with open(chr_list,'r') as file:
    chr_list = file.read().strip().split()

# Read VCF file path as a list
with open(chr_vcf_list,'r') as file:
    chr_vcf_list = file.read().strip().split()

# Split the Dinvestigate windows by chromosome (1-based, sorted)
local_D_windows = {}
with open(local_D_bed,'r') as file:
    for line in file:
        chr, start, end = line.split()[:3]
        local_D_windows.setdefault(chr, []).append((int(start), int(end)))
missing_chr = set(chr_list) - set(local_D_windows)
if missing_chr:
    raise ValueError(f'No Dinvestigate window for chromosome(s) {sorted(missing_chr)}')

# Generate pixy slurm script for every chromosome
for chr, vcf in zip(chr_list, chr_vcf_list):
    print(f'Generating slurm script for chromosome {chr} ...')
    if chr not in vcf:
        raise ValueError(
            f'Chromosome ID {chr} does not match VCF file name {vcf}')

    sub_script_prefix = script_basename+'.'+chr
    chr_bed = os.path.join(output_dir,chr+'.local_D_windows.1based.bed')
    with open(chr_bed,'w') as file:
        for start, end in sorted(local_D_windows[chr]):
            file.write(f'{chr}\t{start}\t{end}\n')
    slurm_content = f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version},
# at {start_time:%Y-%m-%d %H:%M:%S}

#SBATCH -J {sub_script_prefix}
#SBATCH -o {sub_script_prefix}.%J.out
#SBATCH -e {sub_script_prefix}.%J.err
#SBATCH -c 10
#SBATCH --mem=20G

# Set up environment
source "{bin_dir}/s00.config.sh"
# ${{LOAD_PIXY}}
# ${{LOAD_BCFTOOLS}}
${{LOAD_CONDA}}
${{ACTIVATE_PIXY}}



pixy --stats pi \\
    --vcf {vcf} \\
    --populations {pop_path} \\
    --n_cores 10 \\
    --bed_file {chr_bed} \\
    --output_folder {output_dir} \\
    --output_prefix {sub_script_prefix} \\
    --bypass_invariant_check no

# Window size not valid if bed file is provided 
#   
#   --window_size 10000 \\
'''
    # Write slurm script to file
    file = open(os.path.join(sub_script_dir,sub_script_prefix+'.sh'),'w')
    file.write(slurm_content)
    file.close()


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
