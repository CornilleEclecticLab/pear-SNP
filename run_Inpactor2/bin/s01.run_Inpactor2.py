#     This script is used to generate slurm scripts for running Inpactor2 on multiple fasta files.
#     It reads a list of fasta files from an input directory, creates a dictionary mapping each folder to its corresponding fasta file path,
#     and then generates a separate slurm script for each folder in the output directory.
#     Each slurm script runs Inpactor2 on the corresponding fasta file using the specified parameters.
#     The output directory structure is organized based on the folder names.


import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

# Define variables
version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)

# Read the input file and create a dictionary mapping each folder to its corresponding fasta file path
path_dic  = {}
with open(os.path.join(input_dir,'assembly_fasta_files_list.txt'),'r') as io:
    lines = io.readlines()
    for line in lines:
        path = line.strip()
        print(path)
        folder = os.path.basename(os.path.dirname(path))
        if path_dic.get(folder,None) is None:
            path_dic[folder] = path
        else:
            raise ValueError(f'Duplicated fasta files in the folder: {folder}. Please check the fasta_file_list.txt')

# Write the slurm script for running Inpactor2 for each folder
header =f'''#!/usr/bin/env bash
# This slurm file is generated by s01.run_Inpactor2.py, version=${version}, at {start_time}
'''
for folder, path in path_dic.items():
    with open(os.path.join(
        sub_script_dir,'s01.run_Inpactor2.'+folder+'.sh'),'w') as fo:

        output_dir=os.path.join(output_dir,folder)
        os.makedirs(output_dir, exist_ok=True)

        content = f'''
#SBATCH -J s01.run_Inpactor2.sh
#SBATCH -o s01.run_Inpactor2.sh.%J.out
#SBATCH -e s01.run_Inpactor2.sh.%J.err
#SBATCH -c 10
#SBATCH --mem=50G

source activate Inpactor2

python3 \\
    {os.path.join(bin_dir,"Inpactor2.NOGIT.","Inpactor2.py")} \\
    --file {path} \\
    --output-dir {output_dir}
'''
        fo.write(header)
        fo.write(content)

end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))