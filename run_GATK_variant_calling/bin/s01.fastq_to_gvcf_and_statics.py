import datetime, os , getpass
start_time = datetime.datetime.now()
print("{0:=^80}".format(' Start '))



# >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>
# >>>>>              Here is the start fo setting part.                    >>>>>
# >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>

# Set path
user        = getpass.getuser()
work_dir 	= '/work/'+user+'/pear/run_GATK_variant_calling'
group       = 'pear.Zhang2021_b2_p1'


## NO need to change >>
input_dir   = work_dir+'/input'
output_dir  = work_dir+'/output'
prefix      = 's01.fastq_to_gvcf_and_statics.'+group
scripts_dir = work_dir+'/bin/'+prefix
output_dir  = output_dir+'/'+prefix
## NO need to change Change <<



# Set input file names

## The path of a text file record the paths of fastq file, in which, the line starts with # would be ignored, every line for one record(fastq file), and the fastq files of the same sample should be in a same dir with their sample name.
fastq_list = input_dir+"/"+group+".input.clean_data_list.txt"

## Reference genome (fasta) path
ref_genome = input_dir+'/Pyrus_pyrifolia_Cuiguan_Gao2021/GWHBAOS00000000.genome.fasta'

# The path of a txt file records the scaffolds IDs in the reference genome. If there are too many scaffolds, you could save some of them in another file, and write it's path in the following file. In this file,  {input_dir} could be recognized as the variant.
chromosomes = input_dir+'/all_scaffolds.list'



# <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<
# <<<<<                Here is the end fo setting part.                    <<<<<
# <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<



# Ask if run the scripts
run = ''
print("Welcome!")
while run == '':
    run = input("Please chose 1 or 2 to continue: \n\t 1) generate the scripts and run them (submit the jobs using sbatch)\
                \n\t 2) only generate the scripts, without running them.\n")
    
    if run != '1' and run !='2':
        print("Unrecognized input, please try again.\n")
        run = ''

# Read paths of fastq files
with open(fastq_list,'r') as fo:
    
    dic = {}
    for line in fo:
        line = line.strip()
        
        if line.startswith('#'):
            continue
        
        path = line
        file_name = os.path.basename(path)
        dir_name = os.path.basename(os.path.dirname(path))
        sample_name = dir_name
        
        dic[sample_name] = dic.get(sample_name,[])
        dic[sample_name].append(path)
        


# Create dir for saving scripts and output
os.system('mkdir -p '+output_dir)
os.system('mkdir -p '+scripts_dir)

# Change the working dir
os.chdir(scripts_dir)



# Generating the scripts
## Shebang
content_header='''#!/usr/bin/env bash
# This bash script was generated by ../s01.fastq_to_gvcf.py
# For bwa-mem2 mapping, 4 CPU and 32G memory is needed. (6.5G fastq need 20G memory)

'''


## Create scripts for every sample
for sample, path in dic.items():
    
    ## Scripts for mapping, sorting and marking duplicates
    suffix=".Mapping_Sort_MarkDuplicates"
    sample_prefix=sample+suffix
    with open(scripts_dir+"/"+sample_prefix+".sh", 'w') as fo:
        fo.write(content_header)
        
        ## SBATCH settings
        content = '#SBATCH -J '+sample_prefix+' \n'+'#SBATCH -o '+sample_prefix+'.out \n' +'#SBATCH -e '+sample_prefix+'.err \n'
        fo.write(content)

        ## Load softwares
        content = '''
module purge

module load bioinfo/bwa-mem2-2.2
module load bioinfo/samtools-1.14
module load bioinfo/gatk-4.1.9.0


'''
        fo.write(content)
 
        content = '# Bwa-mem2 mapping, samtools sort, .cram \n\nbwa-mem2.sse41 mem -t 4 ' + \
            ref_genome + ' \\\n'
        fo.write(content)

        zcat = ''
        for fasq in path:
            zcat += "'<zcat "+fasq+"' \\\n"
        fo.write(zcat)
        
        content='''-R '@RG\\tID:{sample}\\tSM:{sample}' \\
| samtools sort \\
-@4 -m 4G -l 0 -O bam \\
| samtools view \\
-T {ref_genome} \\
-C -o {output_dir}/{group}.{sample}.sorted.cram - \\
|| {{ echo 'Mapping and sort cram failed' ; exit 1 ; }} 


# Statistic
samtools depth \\
-a {output_dir}/{group}.{sample}.sorted.cram \\
| awk '{{c++;s+=$3}}END{{print s/c}}' > {output_dir}/{group}.{sample}.sorted.avg_depth.txt 

samtools depth \\
-a {output_dir}/{group}.{sample}.sorted.cram \\
| awk '{{c++; if($3>0) total+=1}}END{{print (total/c)*100}}' > {output_dir}/{group}.{sample}.sorted.breadth_coverage.txt 


# GATK MarkDuplicates, .bam
gatk --java-options "-Xmx8g" MarkDuplicates \\
-I {output_dir}/{group}.{sample}.sorted.cram \\
-R {ref_genome} \\
-O {output_dir}/{group}.{sample}.sorted.markdu.bam \\
--REMOVE_DUPLICATES \\
-M {output_dir}/{group}.{sample}.sorted.markdu_metrics.txt \\
|| {{ echo 'Mark duplicate failed' ; exit 1 ; }} 


# Statistic
samtools depth -a {output_dir}/{group}.{sample}.sorted.markdu.bam \\
| awk '{{c++;s+=$3}}END{{print s/c}}' > {output_dir}/{group}.{sample}.sorted.markdu.avg_depth.txt

samtools depth -a {output_dir}/{group}.{sample}.sorted.markdu.bam \\
| awk '{{c++; if($3>0) total+=1}}END{{print (total/c)*100}}' > {output_dir}/{group}.{sample}.sorted.markdu.breadth_coverage.txt 
    

# Remove the mapped cram file
rm {output_dir}/{group}.{sample}.sorted.cram


# Bam to cram, .cram
samtools view -T {ref_genome} \\
{output_dir}/{group}.{sample}.sorted.markdu.bam \\
-o {output_dir}/{group}.{sample}.sorted.markdu.cram \\
|| {{ echo 'Bam to cram failed' ; exit 1 ; }} 


# Remove the bam file
rm {output_dir}/{group}.{sample}.sorted.markdu.bam


# Samtools index cram file 
samtools index {output_dir}/{group}.{sample}.sorted.markdu.cram \\
|| {{ echo 'Index cram failed' ; exit 1 ; }}
\
            '''.format(sample=sample,ref_genome=ref_genome,output_dir=output_dir,group=group)
        fo.write(content)
        
        
    ## Submit this script as a job
    if run == '1':
        command = "sbatch -c 4 --mem=32G "+scripts_dir+"/"+sample_prefix+".sh"
        submit  = os.popen(command, 'r')
        job_id  = submit.read().strip().split()[-1]
        print("\n\nInformation: Dealing with "+ group +' '+ sample )
        print("\nInformation: A job has been submitted: \n\t"+command +'\n')
        
    
    ## Scripts for variant calling
    with open(chromosomes,'r') as fo:
        chromosome = fo.read().strip().format(input_dir=input_dir).split()

        
    for chr in chromosome:
        suffix=".VariantCalling"        
        chr_base = os.path.splitext(os.path.basename(chr))[0]
        sample_prefix_chr = sample + suffix + '.' + chr_base
        
        with open(scripts_dir+"/"+sample_prefix_chr+".sh",'w') as fo:
            fo.write(content_header)
            
            ## SBATCH settings
            content = '#SBATCH -J '+sample+'.'+chr.split('/')[-1]+' \n'+'#SBATCH -o ' + \
                      sample_prefix_chr+'.out \n' + '#SBATCH -e '+sample_prefix_chr+'.err \n\n'
            fo.write(content)

            ## Load softwares
            content = 'module purge \nmodule load bioinfo/gatk-4.1.9.0 \n\n'
            fo.write(content)
        
            ## Call SNPs
            content = '''
# Call SNPs, .g.vcf.gz
gatk --java-options "-Xmx8g" HaplotypeCaller \\
-R {ref_genome} \\
-L {chr} \\
-ploidy 2 \\
--emit-ref-confidence GVCF \\
-I {output_dir}/{group}.{sample}.sorted.markdu.cram \\
-O {output_dir}/{group}.{sample}.{chr_base}.g.vcf.gz \\
|| {{ echo 'HaplotypeCaller Call SNP failed' ; exit 1 ; }}

# Index gvcf
gatk --java-options "-Xmx8g" IndexFeatureFile \\
-I {output_dir}/{group}.{sample}.{chr_base}.g.vcf.gz \\
|| {{ echo 'Index gvcf failed' ; exit 1 ; }}
\
                '''.format(ref_genome=ref_genome,chr=chr,output_dir=output_dir,sample=sample,group=group,chr_base=chr_base)
            fo.write(content)
            
        ## Submit this script as a job
        if run == '1':
            command = "sbatch -c 4 --mem=10G --dependency=afterok:"+job_id+' '+scripts_dir+"/"+sample_prefix_chr+".sh"
            submit = os.popen(command, 'r')
            print("Information: A job has been submitted: \n\t"+command+'\n')
        




end_time = datetime.datetime.now()
print('')
print(' END '.center(80,'='))
print(str(end_time-start_time).center(80))
