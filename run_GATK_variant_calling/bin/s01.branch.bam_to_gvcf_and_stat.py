import datetime,os,warnings
start_time = datetime.datetime.now()
print("{0:=^40}".format(' Start '))

group = 'ECLECTIC'
work_dir = '/work/zruilin/pear/run_GATK_variant_calling'
input_dir = work_dir+'/input'
bin_dir  = work_dir+'/bin/s01.branch.bam_to_gvcf_and_statics.'+group
output_dir = work_dir + '/output/s01.branch.bam_to_gvcf_and_statics.'+group

os.system('mkdir -p '+bin_dir)
os.system('mkdir -p '+output_dir)


samples = dict()
bam_list = input_dir+'/pear.ECLECTIC.input.bam_list.txt'
with open(bam_list,'r') as fr:
    
    for line in fr:
        line = line.strip()
        
        if line == '':
            continue
        
        if line.startswith('#'):
            continue
        
        sample = os.path.basename(os.path.dirname(line))
        if sample not in samples.keys():
            samples[sample]=line
        else:
            warnings.warn('[ERROR]:Duplicated samples')
            exit()
        


head  = '''#!/usr/bin/env bash
# This bash script was generated by ../s01.fastq_to_gvcf.py
#  2 CPU and 10G memory is needed. 

'''

for sample in samples.keys():
    with open(bin_dir+'/s01.'+sample+'.BamVariantCalling.scaffolds.sh','w') as fw:
        fw.write(head)
        
        context= '''
#SBATCH -J {sample}.scaffolds.list
#SBATCH -o {sample}.BamVariantCalling.scaffolds.out
#SBATCH -e {sample}.BamVariantCalling.scaffolds.err

module purge
module load bioinfo/gatk-4.1.9.0
module load bioinfo/samtools-1.14

# Statistic
samtools depth -a {bam} \\
| awk '{{c++;s+=$3}}END{{print s/c}}' > {output_dir}/pear.{group}.{sample}.sorted.markdu.avg_depth.txt

samtools depth -a {bam} \\
| awk '{{c++; if($3>0) total+=1}}END{{print (total/c)*100}}' > {output_dir}/pear.{group}.{sample}.sorted.markdu.breadth_coverage.txt

# Samtools index bam file
samtools index {bam} \\
|| {{echo 'Index bam failed' ; exit 1 ; }}

# Call SNPs, .g.vcf.gz
gatk --java-options "-Xmx8g" HaplotypeCaller \\
    -R /work/zruilin/pear/run_GATK_variant_calling/input/Pyrus_pyrifolia_Cuiguan_Gao2021/GWHBAOS00000000.genome.fasta \\
    -L /work/zruilin/pear/run_GATK_variant_calling/input/scaffolds.list \\
    -ploidy 2 \\
    --emit-ref-confidence GVCF \\
    -I {bam} \\
    -O {output_dir}/pear.{group}.{sample}.scaffolds.g.vcf.gz \\
|| {{echo 'HaplotypeCaller Call SNP failed' ; exit 1 ; }}

# Index gvcf
gatk --java-options "-Xmx8g" IndexFeatureFile \\
    -I {output_dir}/pear.{group}.{sample}.scaffolds.g.vcf.gz \\
|| {{echo 'Index gvcf failed' ; exit 1 ; }}
'''.format(sample=sample,bam=samples[sample],group=group,output_dir=output_dir)

        fw.write(context)
        


end_time = datetime.datetime.now()
print('')
print(' END '.center(40,'='))
print(str(end_time-start_time).center(40))
