import datetime, os
from re import S
import re
from weakref import ref
start_time = datetime.datetime.now()
print("{0:=^40}".format(' Start '))


# Set path
work_dir 	= '/work/zruilin/pear/run_GATK_variant_calling'
group       = '.pear'


## Need NOT Change >>
input_dir   = work_dir+'/input'
output_dir  = work_dir+'/output'
prefix      = 's01.fastq_to_gvcf'+group
scripts_dir = work_dir+'/bin/'+prefix
output_dir  = output_dir+'/'+prefix
## Need NOT Change <<



# Set input file names
## A text file record the paths of fastq file, in which, the line starts with # would be ignored, every line for one record(fastq file), and the fastq files of the same sample should be in a same dir with their sample name.
fastq_list = input_dir+"/input.clean_data_list.txt"
ref_genome = input_dir+'/Pyrus_pyrifolia_Cuiguan_Gao2021/GWHBAOS00000000.genome.fasta'


# Read paths of fastq files
dic = {}
with open(fastq_list,'r') as fo:
    for line in fo:
        line = line.strip()
        
        if line.startswith('#'):
            continue
        
        path = line
        file_name = os.path.basename(path)
        dir_name = os.path.basename(os.path.dirname(path))
        sample_name = dir_name
        
        dic[sample_name] = dic.get(sample_name,[])
        dic[sample_name].append(path)
        


# Create dir for saving scripts and output
os.system('mkdir -p '+scripts_dir)
os.system('mkdir -p '+output_dir)



# generating the scripts
## Shebang
content_header='''#!/usr/bin/env bash
# bash file generated by ../s01.fastq_to_gvcf.py

'''


## create scripts for every sample
suffix=".Mapping_Sort_MarkDuplicates"
for sample, path in dic.items():
    sample_prefix=sample+suffix
    with open(scripts_dir+"/"+sample_prefix+".sh", 'w') as fo:
        fo.write(content_header)
        
        ## SBATCH settings
        content = '# SBATCH -J '+sample_prefix+' \n'+'#SBATCH -o '+sample_prefix+'.out \n' +'#SBATCH -e '+sample_prefix+'.err \n'
        fo.write(content)

        ## load softwares
        content = '''module purge

module load bioinfo/bwa-mem2-2.0
module load bioinfo/samtools-1.14
module load bioinfo/gatk-4.1.7.0

'''
        fo.write(content)
 
        content='# mem2 mapping, samtools sort, .cram \nbwa-mem2 mem -t 4 ' + ref_genome + ' \\\n'
        fo.write(content)

        zcat = ''
        for fasq in path:
            zcat += "'<zcat "+fasq+"' \\\n"
        fo.write(zcat)
        
        content='''-R '@RG\\tID:{sample}\\tSM:{sample}' \\
| samtools sort -@4 -m 4G -l 0 -O bam \\
| samtools view -T {ref_genome} \\
-C -o {output_dir}/{sample}{group}.sorted.cram \\
|| {{ echo 'mapping and sort cram failed' ; exit 1 ; }} 

# gatk MarkDuplicates, .bam
gatk --java-options "-Xmx8g" MarkDuplicates -I {output_dir}/{sample}{group}.sorted.cram \\
-R {ref_genome} \\
-O {output_dir}/{sample}{group}.sorted.markdu.bam \\
-- REMOVE_DUPLICATES \\
-M {output_dir}/{sample}{group}.sorted.markdu_metrics.txt \\
|| {{ echo 'Mark duplicate failed' ; exit 1 ; }} 

rm {output_dir}/{sample}{group}.sorted.cram

# bam to cram
samtools view -T {ref_genome} \\
{output_dir}/{sample}{group}.sorted.markdu.bam \\
-o {output_dir}/{sample}{group}.sorted.markdu.cram \\
|| {{ echo 'bam to cram failed' ; exit 1 ; }} 

rm {output_dir}/{sample}{group}.sorted.markdu.bam

# samtools index cram file 
samtools index {output_dir}/{sample}{group}.sorted.markdu.cram \\
|| {{ echo 'index cram failed' ; exit 1 ; }}

'''.format(sample=sample,ref_genome=ref_genome,output_dir=output_dir,group=group)
        fo.write(content)

end_time = datetime.datetime.now()
print('')
print(' END '.center(40,'='))
print(str(end_time-start_time).center(40))
