import datetime
import os
import sys
start_time = datetime.datetime.now()
print("{0:=^79}".format(' Start '))



# >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>
# >>>>>                Here is the start fo setting part.                  >>>>>
# >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>


# Set the parameters for sbatch
account='pear_snp3'
mem_bcftools_filter = '32G'
mem_gatk_filter = '32G'
mem_gatk_java = '30g'

## /!\ To check the output4_dir, and keep variant "group" same with the filename header /!\
group = 'pear_July2023' # group name in the output4_dir
group_new = 'pear_July2023' # group name in the output5_dir


## NO need to change >>
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir, 'input')
output_dir = os.path.join(work_dir, 'output')
prefix = 's05.hard_filter_chr_vcf.' + group_new
prefix2 = 's05.variant_invariant_concat.' + group_new
scripts_dir = os.path.join(work_dir, 'bin','s05.hard_filter_chr_vcf_and_variant_invariant_concat.'+group_new)
output4_dir = os.path.join(output_dir, 's04.combine_chr_gvcf_to_vcf_allsites.'+group)
output5_dir = os.path.join(output_dir, prefix)
tmp_dir = os.path.join(work_dir, 'gatk_tmp')


## NO need to change Change <<



# Set input file names


## Reference genome (fasta) path
ref_genome = os.path.join(input_dir, 'Pyrus_pyrifolia_Cuiguan_Gao2021/GWHBAOS00000000.genome.fasta')

# The path of a txt file records the scaffolds IDs in the reference genome. If there are too many scaffolds, you could save some of them in another file, and write it's path in the following file. In this file, {input_dir} could be recognized as the variant.
chromosomes = os.path.join(input_dir, 'all_scaffolds.list')



# <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<
# <<<<<                Here is the end fo setting part.                    <<<<<
# <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<



# Ask if run the scripts
run = ''
print("Welcome!")
while run == '':
    run = input("Please chose 1 or 2 to continue: \
\n\t1) generate the scripts and run them\(submit the jobs using sbatch)\
\n\t2) only generate the scripts, without running them.\n")

    if run != '1' and run !='2':
        print("Unrecognized input, please try again.\n")
        run = ''



# Create dir for saving scripts and output
os.system('mkdir -p ' + scripts_dir)
os.system('mkdir -p ' + output5_dir)
os.system('mkdir -p ' + tmp_dir)


# Change the working dir
os.chdir(scripts_dir)


# Record the job ID
if run=="1":
    job_id_txt = open(os.path.join(scripts_dir, 'job_ID.txt'),'w')


# Create the g.vcf.gz file list for every scaffold
## Read chromosomes list
with open(chromosomes,'r') as fo:
    chromosome = fo.read().strip().format(input_dir=input_dir).split()


for chr in chromosome:
    suffix =".VariantCalling"
    chr_base = os.path.splitext(os.path.basename(chr))[0]

    ## Create the hard filter bash script
    sh = os.path.join(scripts_dir, prefix+'.'+chr_base+'.sh')
    with open(sh,'w') as fo: 
        # Shebang
        content_header = f"#!/usr/bin/env bash \n# bash file generated by ../{str(__file__)} at {str(datetime.datetime.now())} \n\n"
        fo.write(content_header)

        ## SBATCH settings
        content = f'''#SBATCH -J s05.H.{chr_base} 
#SBATCH -o {prefix}.{chr_base}.%J.out
#SBATCH -e {prefix}.{chr_base}.%J.err
'''
        fo.write(content)

        ## Load softwares
        softwares = '''
module purge

module load bcftools/1.14


'''
        fo.write(softwares)

        ## bcftools filter, .vcf.gz
        content = '''

# Filter all the site don't have QUAL, FILTER, INFO by filter F_MISSING = 1

bcftools filter -e 'F_MISSING = 1' \\
    {output4_dir}/{group}.{chr_base}.combine.vcf.gz \\
    -O z4 \\
    -o {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.vcf.gz \\
    --threads 4 \\
|| {{ echo "rmQFI failed!" ; exit 1 ; }} 

tabix {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.vcf.gz


# Load gatk
module load gatk4/4.1.9.0


# You can use -XL to remove scaffold like mitochondria

# Soft filter, annotate the vcf

gatk --java-options "-Xmx{mem_gatk_java} -Djava.io.tmpdir={tmp_dir}" VariantFiltration \\
    -R {ref_genome} \\
    -V {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.vcf.gz \\
    --filter-name "badSeq" \\
    --filter-expression "(vc.isSNP() && (vc.hasAttribute('ReadPosRankSum') && ReadPosRankSum < -8.0)) || ((vc.isIndel() || vc.isMixed()) && (vc.hasAttribute('ReadPosRankSum') && ReadPosRankSum < -20.0)) || (vc.hasAttribute('QD') && QD < 2.0) " \\
    --filter-name "badStrand" \\
    --filter-expression "(vc.isSNP() && ((vc.hasAttribute('FS') && FS > 60.0) || (vc.hasAttribute('SOR') &&  SOR > 3.0))) || ((vc.isIndel() || vc.isMixed()) && ((vc.hasAttribute('FS') && FS > 200.0) || (vc.hasAttribute('SOR') &&  SOR > 10.0)))" \\
    --filter-name "badMap" \\
    --filter-expression "vc.isSNP() && ((vc.hasAttribute('MQ') && MQ < 40.0) || (vc.hasAttribute('MQRankSum') && MQRankSum < -12.5))" \\
    --filter-name "lowQUAL" \\
    --filter-expression "(vc.isSNP() || vc.isIndel() || vc.isMixed()) && (QUAL < 30.0)" \\
    -O {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.filter_anno.vcf.gz \\
|| {{ echo "Annotate the vcf failed!" ; exit 1 ; }} 


# Hard filter, remove entries

gatk --java-options "-Xmx{mem_gatk_java} -Djava.io.tmpdir={tmp_dir}" SelectVariants \\
    -R {ref_genome} \\
    -V {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.filter_anno.vcf.gz \\
    --exclude-filtered true \\
    -O {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.filter_passed_sites.vcf.gz \\
|| {{ echo "Generate the passed vcf failed!" ; exit 1 ; }} 

'''.format(ref_genome=ref_genome,output4_dir=output4_dir,chr_base=chr_base,output5_dir=output5_dir,group=group,group_new=group_new,tmp_dir=tmp_dir,mem_gatk_java=mem_gatk_java)
        fo.write(content)

    ## Submit this script as a job
    if run == '1':
        command = f"sbatch -c 4 --mem={mem_gatk_filter} -A {account} {sh}"
        submit = os.popen(command, 'r')
        current_job_id = submit.read().strip().split()[-1]
        depended_job_id = current_job_id
        job_id_txt.write(sh + '\t' + current_job_id + '\n')
        print("\n\nInformation: Dealing with "+ group_new + ' ' + chr_base)
        print("\nInformation: A job has been submitted: \n\t" + command +'\n')


    # Generating the variant invariant concat scripts
    sh2 = os.path.join(scripts_dir, prefix2+'.'+chr_base+'.sh')
    with open(sh2, 'w') as fo:
        # Shebang
        content_header = f"#!/usr/bin/env bash \n#bash file generated by ../{str(__file__)} at {str(datetime.datetime.now())} \n\n "

        fo.write(content_header)

        # SBATCH settings
        content = f'''#SBATCH -J s05.C.{chr_base} 
#SBATCH -o {prefix2}.{chr_base}.%J.out
#SBATCH -e {prefix2}.{chr_base}.%J.err
'''
        fo.write(content)


        # Load softwares
        fo.write(softwares)

        # bcftools filter, .vcf.gz
        content = '''
bcftools filter -S . -e 'FMT/DP<3 | FMT/RGQ<20 | FMT/DP>100' \\
    {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.filter_passed_sites.vcf.gz \\
| bcftools filter -i 'ALT="."' \\
| bcftools filter -e 'F_MISSING > 0.2' \\
    -O z4 --threads 4 \\
    -o {output5_dir}/{group_new}.{chr_base}.filtered_pixy_invariant.vcf.gz
        
tabix -p vcf {output5_dir}/{group_new}.{chr_base}.filtered_pixy_invariant.vcf.gz


bcftools filter -S . -e 'FMT/DP<3 | FMT/GQ<20 | FMT/DP>100' \\
    {output5_dir}/{group_new}.{chr_base}.rmQFI.combine.filter_passed_sites.vcf.gz \\
| bcftools filter --SnpGap 10 \\
| bcftools view -m2 -M2 -v snps \\
| bcftools filter -e 'F_MISSING > 0.2' \\
    -O z4 --threads 4 \\
    -o {output5_dir}/{group_new}.{chr_base}.filtered_pixy_variant.vcf.gz

tabix -p vcf {output5_dir}/{group_new}.{chr_base}.filtered_pixy_variant.vcf.gz


bcftools concat \\
    --allow-overlaps \\
    {output5_dir}/{group_new}.{chr_base}.filtered_pixy_invariant.vcf.gz \\
    {output5_dir}/{group_new}.{chr_base}.filtered_pixy_variant.vcf.gz \\
    -O z4 --threads 4 \\
    -o {output5_dir}/{group_new}.{chr_base}.filtered_pixy_concat.vcf.gz

tabix -p vcf {output5_dir}/{group_new}.{chr_base}.filtered_pixy_concat.vcf.gz

'''.format(chr_base=chr_base, output5_dir=output5_dir, group_new=group_new)
        fo.write(content)

    # Submit this script as a job
    if run == '1':
        continue # Don't running the script as the hard filter threshold is unsure
        command = f"sbatch -p long -c 4 -A {account} --mem={mem_bcftools_filter} --dependency=afterok:{depended_job_id} {sh2}"
        submit = os.popen(command, 'r')
        current_job_id = submit.read().strip().split()[-1]
        job_id_txt.write(sh2 + '\t' + current_job_id + '\n')
        print("Information: A job has been submitted: \n\t" + command + '\n')

if run == '1':
    job_id_txt.close()



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
