import datetime
import textwrap
import os
import sys
import numpy as np
import re
import glob
from s01_config import *
from s00_config import *


start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.1"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir,exist_ok=True)


# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Read the input individuals list
# Individuals list Table content:
# ID_vcf    ID_uni  Pop    Depth    Reads_length

# Note: the ID_uni is not used in this script
pop_dic = {}
ind_list = []
with open(individuals_table, "r") as fr:
    for line in fr:
        if line.startswith("#"):
            continue
        line = line.strip()

        if line=='':
            continue
        line = line.split()
        # Here id_uni is not used in this script.
        id, id_uni, pop, depth, reads_length = line

        if float(depth) < 20:
            raise ValueError("Depth is less than 20 for ID: {}".format(id))

        if id in ind_list:
            raise ValueError("Duplicated IDs in tables: {}".format(id))

        ind_list.append(id)
        # print(id, pop, depth, reads_length,line)
        pop_dic[pop] = pop_dic.get(pop,[])
        pop_dic[pop].append([id,depth,reads_length])


# Check the length std dev
for pop, inds in pop_dic.items():
    reads_lengths = [float(values[2]) for values in inds]
    average_length = np.average(reads_lengths)
    std_dev_length = np.std(reads_lengths)

    print("{}\tAverage_length:{}\tStd_dev:{}".format(pop,average_length,std_dev_length))

    if std_dev_length > 10:
        raise  ValueError(f'Jagged reads length in Population: {pop}')


# Read the cram file paths and check the file existence:
cram_paths = glob.glob(cram_dir)
file_names = []
id_path_check_dic = {}
for path in cram_paths:
    if not os.path.exists(path):
        raise FileNotFoundError("File does not exist: {}".format(path))
    else:
        file_name = os.path.basename(path)
        file_names.append(file_name)
    # Note: the cram/bam file names may have different formats
        id = file_name.split(".")[-4]
        id_path_check_dic[id] = path

# Check the cram file path
for id in ind_list:
    file_name_str = '\t'.join(file_names)
    if id not in file_name_str:
        raise ValueError(f"Didn't find the cram/bam file path for this ID: {id}")


# Write the sub_script for running MEGAnE by individuals
header = f'''#!/bin/bash
# This script was generated by ../s01.generage_MEGAnE_genotype_calling_scripts.py
# Version {version}
# Time {start_time}
'''

for pop, values in pop_dic.items():
    ids = [i[0] for i in values]
    for id in ids:
        path = id_path_check_dic[id]
        path_basename = os.path.basename(path)
    # Note: the cram/bam file names may have different formats
        match_format = (re.match(r"^(.+?)(\..+?)(\.)(.+?)(\.)",path_basename).group(4))

        if id not in path_basename or id != match_format:
            raise ValueError("Unmatched id and path:\n {}\n {}".format(id,path))
        outdir = os.path.join(output_dir,pop,id)
        os.makedirs(outdir, exist_ok=True)
        sub_script = f"s01.call_and_genotype_polymorphic_MEs.{id}.sh"
        fo = open(os.path.join(sub_script_dir, sub_script), "w")
        cpu = "4"
        content = f'''
#SBATCH -J s01.{id}.sh
#SBATCH -o {sub_script}.%J.out
#SBATCH -e {sub_script}.%J.err
#SBATCH -c {cpu}      # Booked 16 from slurm and also assigned 16 to MEGAnE but used 4 cores during testing. Job ID: 38787863
#SBATCH --mem=50G     # Booked 120G but used 39.36G during testing. Time 04:18:04

source "{bin_dir}/s00_config.sh"

singularity exec ${{sif}} call_genotype \\
    -i {path} \\
    -fa {input_dir}/{ref_genome_fa} \\
    -mk {input_dir}/megane_kmer_set/{mk_file_prefix}.mk \\
    -fadb {input_dir}/ref_genome_blastdb/{ref_genome_fa} \\
    -rep {input_dir}/{rep_library_fa}\\
    -repout {input_dir}/{repeatmask_out} \\
    -repremove {input_dir}/non_ME_rep.txt \\
    -pA_ME {input_dir}/ME_with_pA.txt \\
    -mainchr {input_dir}/main_chr_list.txt \\
    -sample_name {id} \\
    -no_sex_chr \\
    -outdir {outdir} \\
    -p {cpu}
    # -skip_unmapped
'''
        fo.write(header)
        fo.write(content)
        fo.close()



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
