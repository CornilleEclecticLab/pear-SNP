import datetime
import sys
import textwrap
import os
import random
from s00_config import *

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output')
sub_output_dir = os.path.join(output_dir,script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

# Ensure output directory exists
os.makedirs(sub_output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Read individuals list with population
ind_list = os.path.join(input_dir, sample_populations_filename)

with open(ind_list,'r') as f:
    lines = f.read().strip().split('\n')
    population_individuals = {}
    for line in lines:
        ind,pop = line.split()
        population_individuals[pop] = population_individuals.get(pop,[]) + [ind]


# Get the random sample of individuals
print("Sampling Summary:")
sampling_record = open(os.path.join(sub_output_dir,'sampling_record.txt'), 'w')
for i in range(1,1001):
    ind_list_file = os.path.join(sub_output_dir,f'indviduals_replicate{i}.txt')
    ind_to_pop_file = os.path.join(sub_output_dir,f'ind_to_pop_replicate{i}.txt')
    sampling_record.write(f'Replicate_{i}\t')
    with open(ind_list_file,'w') as fi, open(ind_to_pop_file,'w') as fip:
        for pop, inds in population_individuals.items():
            random.shuffle(inds)
            s_ind = inds[0]
            fi.write(s_ind+'\n')
            fip.write(f'{s_ind}\t{pop}\n')
            sampling_record.write(f'{pop}:{s_ind}\t')
            # print(f'{pop}:{s_ind}')
        sampling_record.write('\n')
        print('')
    fi.close()
    fip.close()
sampling_record.close()


input_vcf=os.path.join(input_dir,input_vcf_filename)

header = f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""
sub_script_base = script_basename
with open(os.path.join(sub_script_dir, sub_script_base+'.sh'), 'w') as fo:
    fo.write(header)
    
    ind_list_file_prefix = os.path.join(sub_output_dir,f'indviduals_replicate')
    ind_to_pop_file_prefix = os.path.join(sub_output_dir,f'ind_to_pop_replicate')
    output_vcf_prefix = os.path.join(sub_output_dir,f'replicate')
    fo.write(f"""
#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH -c 1
#SBATCH --mem=1G
#SBATCH --array=1-1000
#SBATCH --exclude=cpu-node-17


module purge
module load bcftools/1.14

bcftools view \\
    {input_vcf} \\
    -S {ind_list_file_prefix}${{SLURM_ARRAY_TASK_ID}}.txt \\
| bcftools view \\
    -e 'F_MISSING > 0.1 || AC==0 || AN==AC' \\
    -o {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.vcf

bcftools reheader \\
    {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.vcf \\
    -s {ind_to_pop_file_prefix}${{SLURM_ARRAY_TASK_ID}}.txt \\
    -o {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.vcf


module unload bcftools
source ~/.bashrc
conda activate biopython

python {bin_dir}/vcf2phylip.py \\
    -r \\
    -i {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.vcf \\
    --output-folder {sub_output_dir}
    
python {bin_dir}/s01.a.phy_invariant_cleaner.py \\
    -i {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.min4.phy \\
    -o {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.varsites.phy


conda deactivate
conda activate iqtree-2.3.6

iqtree \\
    -s {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.varsites.phy \\
    -m GTR+ASC \\
    -B 1000 \\
    --boot-trees \\
    -T AUTO \\
    -pre {output_vcf_prefix}${{SLURM_ARRAY_TASK_ID}}.reheader.varsites 
""")

end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
