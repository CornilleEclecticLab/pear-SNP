import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output')
sub_output_dir = os.path.join(output_dir,script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

import s01_config as cfg

# Ensure output directory exists
os.makedirs(sub_output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Load vcf file path
pop_vcf_dic = dict()
with open(cfg.vcf_file_list, 'r') as fi:
    for line in fi:
        line = line.strip()
        basename = os.path.basename(line)
        fields = basename.split('.')

        chrom, pop, fmt = fields[-3:]
        
        if pop in cfg.population_sample_dic and chrom in cfg.chr_list:
            pass
        else:
            if pop not in cfg.population_sample_dic:
                print(f"WARNING: {line} pop {pop} not in population dictionary")
            if chrom not in cfg.chr_list:
                print(f"WARNING: {line} chrom {chrom} not in chrom list file")
            raise ValueError(f'{pop} {chrom}')
        
        if pop not in pop_vcf_dic:
            pop_vcf_dic[pop] = dict()

        if chrom not in pop_vcf_dic[pop]:
            pop_vcf_dic[pop][chrom] = line
        else:
            raise ValueError(f'Chrom {chrom} has multiple vcf files for pop {pop}')

    

header = f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""

for pop, chroms in pop_vcf_dic.items():
    if len(chroms) != len(cfg.chr_list):
        raise ValueError(f'Chroms number not match for pop {pop}')
    vcf_list =' '.join([chroms[c] for c in chroms])
    output_vcf = os.path.join(sub_output_dir, f'rohan.{pop}.vcf.gz')
    stat_file = os.path.join(sub_output_dir, f'rohan.{pop}.stats.txt')
    tstv_file = os.path.join(sub_output_dir, f'rohan.{pop}.tstv.txt')
    sub_script_base = f'tstv.{pop}'

    with open(os.path.join(sub_script_dir, sub_script_base+'.sh'), 'w') as fo:
        fo.write(header)
        fo.write(f"""
#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH -c 4
#SBATCH --mem=16G

. ../s00.load_bcftools.sh

bcftools concat \\
    {vcf_list} \\
    --threads 4 \\
    -O z \\
    --output {output_vcf}

tabix -p vcf {output_vcf}

bcftools view -R {cfg.bed_file} {output_vcf} \\
| bcftools stats \\
| grep "TSTV" > {stat_file}

grep "^TSTV" {stat_file} |grep -v "#" | awk '{{print $5}}' > {tstv_file}

rm {output_vcf}
rm {output_vcf}.tbi
""")




end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))