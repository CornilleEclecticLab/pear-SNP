import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output')
sub_output_dir = os.path.join(output_dir,script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

import s01_config as cfg

# Ensure output directory exists
os.makedirs(sub_output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Load cram files path
sample_cram_dic = {}
with open(cfg.cram_file_list, 'r') as f:
    for line in f:
        line = line.strip().split()
        cram_name = line[0]
        if not cram_name.endswith('cram'):
            continue
        base_name = os.path.splitext(os.path.basename(cram_name))[0]
        fields = base_name.split('.')

        sample_id = fields[2]

        if sample_id in sample_cram_dic:
            print(f"Duplicate cram for {sample_id}? \ncram {line} \ncram {sample_cram_dic[sample_id]}")

        if sample_id in cfg.sample_population_dic:
            sample_cram_dic[sample_id] = cram_name


for p, samples in cfg.population_sample_dic.items():
    for s in samples:
        if s in sample_cram_dic:
            pass
        else:
            print(f'WARNING: Sample {s} from population {p} not difenied cram file path in cram_file_list')
    

header = f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""
for sample, cram in sample_cram_dic.items():
    pop = cfg.sample_population_dic[sample]
    sub_script_base = f'rohan.{pop}.{sample}'
    pop_output_dir = os.path.join(sub_output_dir, pop)
    
    os.makedirs(pop_output_dir, exist_ok=True)
    
    bam_file = os.path.join(pop_output_dir, f'{sub_script_base}.bam')

    # load tstv
    with open(os.path.join(cfg.tstv_dir, f"rohan.{pop}.tstv.txt"), 'r') as fi:
        tstv = fi.read().strip()
    
    print(f'Load TSTV = {tstv} for pop {pop}')

    with open(os.path.join(sub_script_dir, sub_script_base+'.sh'), 'w') as fo:
        fo.write(header)
        fo.write(f"""
#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH -c 4
#SBATCH --mem=4G



# Cram to bam
. ../s00.load_samtools.sh
samtools view \\
    -@ 4 -b -F 0x600 \\
    -o {bam_file} \\
    -T {cfg.ref_genome} \\
    {cram}

samtools index -@ 4 {bam_file}

# Calculate ROH
. ../s00.load_rohan.sh

rohan \\
    --tstv {tstv} \\
     -t 4 \\
    --auto {cfg.chr_list_file} \\
    --rohmu 1e-3 \\
    --name {sample} \\
    --map {cfg.bed_file} \\
    --out {os.path.join(sub_output_dir, pop, sample)} \\
    {cfg.ref_genome} \\
    {bam_file}

    # --hmm \\

# Mannually run the next steps, as there is no finishing signal from rohan.
# rm {bam_file}

# python3 ../s02.x1.get_ROH_table.py {os.path.join(sub_output_dir, pop, sample+".mid.hmmp.gz")} 

""")



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
