import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

# Define the running batch

batch_name = 'pear_Jul2023_LDdecay'
batch = 'branch8.batch15.'+ batch_name

# Define version and script information
version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
bin_dir = os.path.join(work_dir,'bin')
PopLDdecay_bin = os.path.join(bin_dir,'PopLDdecay','bin')
input_dir = os.path.join(work_dir,'input',batch)
output_dir = os.path.join(work_dir,'output',batch)

# Input files
in_group_list = os.path.join(input_dir,'s02.taxpartitions.txt')
in_vcf = os.path.join(output_dir, batch_name+'.Combine_Chr.geno25_maf0005_for_PopLDdecay.vcf.gz')

# Subscript directories
subscript_dir3 = os.path.join(bin_dir,'s03.run_PopLDdecay')
subscript_dir4 = os.path.join(bin_dir,'s04.plot_LDdecay')
subscript_dir5 = os.path.join(bin_dir,'s05.plot_LDdecay_multi')

# Ensure subscript directories exist
for dir in [subscript_dir3, subscript_dir4, subscript_dir5]:
    os.makedirs(dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)

# Store groups and sample IDs in a dictionary
out_group = {}

# Read group information from input file
with open(in_group_list,'r') as fi:
    fi = fi.read().strip().splitlines()
    for line in fi:
        line = line.split()
        columns = len(line)
        if columns == 2 or 3:
            sample_id = line[columns-2]
            group_id = line[columns-1]
        else:
            print(wrap('Error: Wrong number of columns in input file.'))
            sys.exit(1)
        out_group.setdefault(group_id,[]).append(sample_id)

# Output samples list file for each group
pop_list = os.path.join(output_dir,'s03.stat_pop_list.txt')
fo_pop_list = open(pop_list,'w')

# Shebang for subscripts
sub_shebang = f"#!/usr/bin/env bash\n# This script is generated by ../{script_basename}.py v{version} at {start_time} \n"

# Process each group
for group, ids in out_group.items():
    # Output sample list file for the group
    out_file = os.path.join(output_dir,f's01.sample_list.{group}.txt')
    with open(out_file,'w') as fo:
        for id in ids:
            fo.write(f'{id}\n')

    # Generate PopLDdecay subscript
    subscript_prefix = f's03.run_PopLDdecay.{group}'
    out_stat = os.path.join(output_dir,subscript_prefix+'.stat.gz')
    run_file = os.path.join(subscript_dir3,subscript_prefix+'.sh')
    PopLDdecay = os.path.join(PopLDdecay_bin,'PopLDdecay')
    with open(run_file,'w') as fo:
        fo.write(sub_shebang)
        sbatch_PopLDdecay = f'''
#SBATCH -J {subscript_prefix}
#SBATCH -o {subscript_prefix}.%J.out
#SBATCH -e {subscript_prefix}.%J.err

{PopLDdecay} \\
    -InVCF {in_vcf} \\
    -OutStat {out_stat} \\
    -SubPop {out_file} \\
    -OutType 2 &&\\
'''
        fo.write(sbatch_PopLDdecay)
        fo.write(f'echo "Done!"\n')
        fo.write(f'echo "Finished at $(date)"\n')

        # Write stat output path to pop_list file
        fo_pop_list.write(f'{out_stat}\t{group}\n')

    # Generate PopLDdecay plot subscript
    plot_sh = os.path.join(subscript_dir4,f's04.plot_LDdecay.{group}.sh')
    Plot_OnePop = os.path.join(PopLDdecay_bin,'Plot_OnePop.pl')
    with open(plot_sh,'w') as fo:
        fo.write(sub_shebang)
        plot_PopLDdecay = f'''
module load r

perl {Plot_OnePop} \\
    -keepR \\
    -inFile {out_stat} \\
    -output {output_dir}/s04.plot_LDdecay_{group} \\
    -measure both
'''
        fo.write(plot_PopLDdecay)

# Generate PopLDdecay multi-plot subscript
plot_PopLDdecay_multi = os.path.join(subscript_dir5,'s05.plot_LDdecay_multi.sh')
Plot_MultiPop = os.path.join(PopLDdecay_bin,'Plot_MultiPop.pl')
with open(plot_PopLDdecay_multi,'w') as fo:
    fo.write(sub_shebang)
    fo.write(f'''
module load r

perl {Plot_MultiPop} \\
    -keepR \\
    -inList {pop_list} \\
    -output {output_dir}/s05.plot_LDdecay_multi \\
    -measure both 
''')
    





end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))