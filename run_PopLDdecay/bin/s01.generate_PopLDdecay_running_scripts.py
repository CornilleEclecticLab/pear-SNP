import datetime
import sys
import textwrap
import os
from s00_config import *

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


# Define version and script information
version = "2.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
bin_dir = os.path.join(work_dir, 'bin')
PopLDdecay_bin = os.path.join(bin_dir, 'PopLDdecay.NOGIT.', 'bin')
input_dir = os.path.join(work_dir, 'input')
output_dir = os.path.join(work_dir, 'output')
sub_output_dir = os.path.join(output_dir, script_basename)
sub_bin_dir = os.path.join(bin_dir, script_basename)


# Ensure subscript directories exist
sub_bin_dir2 = os.path.join(bin_dir,'s02.plot_LDdecay_multi')
sub_output_dir2 = os.path.join(output_dir, 's02.plot_LDdecay_multi')

for dir in [sub_output_dir, sub_bin_dir, sub_bin_dir2, sub_output_dir2]:
    os.makedirs(dir, exist_ok=True)


# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Load and read group list from config file
group_id_dict = {}
with open(os.path.join(input_dir, group_list_filename), 'r') as fi:
    in_group_lis = fi.read().strip().splitlines()
    for line in in_group_lis:
        if line.startswith('#'):
            continue
        id, group = line.split()
        group_id_dict[group] = group_id_dict.get(group, []) + [id]


# record the output stat file list
stat_files_path = os.path.join(sub_output_dir, 'stat_files.list.txt')
stat_files = open(stat_files_path, 'w')


# Shebang for subscripts
sub_shebang = f"#!/usr/bin/env bash\n# This script is generated by ../{script_basename}.py v{version} at {start_time} \n"


# Process each group
for i in range(len(group_id_dict)+1):
    if i < len(group_id_dict):
        long_partition = ''
        group, ids = list(group_id_dict.items())[i]
        sub_list = os.path.join(sub_output_dir, f's01.sample_list.{group}.txt')
        with open(sub_list, 'w') as fo:
            for id in ids:
                fo.write(f'{id}\n')
        sub_pop = f'\\\n    -SubPop {sub_list} '
    elif i == len(group_id_dict):
        group = 'ALLsample'
        sub_list = 'ALLsample'
        sub_pop = ''
        long_partition = '#SBATCH --partition=long'
    # Generate PopLDdecay subscript
    in_vcf = os.path.join(input_dir, in_vcf_filename)
    subscript_prefix = f'PopLDdecay.{group}'
    out_stat = os.path.join(sub_output_dir, subscript_prefix+'.stat.gz')
    run_file = os.path.join(sub_bin_dir, subscript_prefix+'.sh')
    PopLDdecay = os.path.join(PopLDdecay_bin, 'PopLDdecay')
    Plot_OnePop = os.path.join(PopLDdecay_bin, 'Plot_OnePop.pl')
    with open(run_file, 'w') as fo:
        fo.write(sub_shebang)
        sbatch_PopLDdecay = f'''
#SBATCH -J {subscript_prefix}
#SBATCH -o {subscript_prefix}.%J.out
#SBATCH -e {subscript_prefix}.%J.err
#SBATCH -c 1
#SBATCH --mem=30G
{long_partition}

# module load r
source {bin_dir}/s00.load_r.sh

{PopLDdecay} \\
    -InVCF {in_vcf} \\
    -OutStat {out_stat} {sub_pop}\\
    -OutType 2 &&\\

perl {Plot_OnePop} \\
    -keepR \\
    -inFile {out_stat} \\
    -output {sub_output_dir}/plot_LDdecay_{group} \\
    -measure both

'''
        fo.write(sbatch_PopLDdecay)
        stat_files.write(f'{out_stat}\t{group.replace("-","_")}\n')
stat_files.close()

# Generate PopLDdecay multi-plot subscript
plot_PopLDdecay_multi = os.path.join(
    sub_bin_dir2, 's02.plot_LDdecay_multi.sh')
Plot_MultiPop = os.path.join(PopLDdecay_bin, 'Plot_MultiPop.pl')
with open(plot_PopLDdecay_multi, 'w') as fo:
    fo.write(sub_shebang)
    fo.write(f'''
module load r

perl {Plot_MultiPop} \\
    -keepR \\
    -inList {stat_files_path} \\
    -output {sub_output_dir2}/s02.plot_LDdecay_multi_both \\
    -measure both 

perl {Plot_MultiPop} \\
    -keepR \\
    -inList {stat_files_path} \\
    -output {sub_output_dir2}/s02.plot_LDdecay_multi_r2 \\
    -measure r2

perl {Plot_MultiPop} \\
    -keepR \\
    -inList {stat_files_path} \\
    -output {sub_output_dir2}/s02.plot_LDdecay_multi_D \\
    -measure D
''')


end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time-start_time).center(79))
