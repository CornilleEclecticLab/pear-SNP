import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output','s02.vcf')
sub_script_dir = os.path.join(bin_dir,script_basename)
phased_vcf_dir = os.path.join(input_dir,'phased_vcf_files')

# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)

# Read chromosome list
with open(os.path.join(input_dir,'s02.chromosome_list.txt'),'r') as fi:
    chr_list = fi.read().strip().split('\n')

# Read individual list
with open(os.path.join(input_dir,'s01.random_individual_population.txt'),'r') as fi:
    ind_list = [line.strip().split()[0] 
                for line in fi.read().strip().split('\n') 
                if not line.startswith('#')]


# Split the merged VCF file by chromosome and individual
header=f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""
for ind in ind_list:
    for chr in chr_list:
        in_vcf = os.path.join(phased_vcf_dir,f'{chr}.phased.vcf.gz')
        sub_script_base = script_basename + f'.{ind}.{chr}'
        out_vcf = os.path.join(output_dir,f'{chr}.{ind}.vcf.gz')
        with open(os.path.join(sub_script_dir,sub_script_base+'.sh'),'w') as fo:
            fo.write(header)
            fo.write(f"""
#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.sh.%J.out
#SBATCH -e {sub_script_base}.sh.%J.err
#SBATCH -c 4
#SBATCH --mem=8G

module load bcftools/1.14

bcftools view \\
    {in_vcf} \\
    -s {ind} \\
    -r {chr} \\
    --threads 4 | \\
bcftools filter \\
    -e 'AN==0' \\
    -Oz4 \\
    --threads 4 \\
    -o {out_vcf}
""")


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
