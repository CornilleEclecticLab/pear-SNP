import datetime
import sys
import textwrap
import os
import warnings

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
bin_dir = script_path
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(work_dir,'bin',script_basename)
chromosomes = os.path.join(input_dir,'all_scaffolds.list')
individual_group_map = os.path.join(input_dir,'s02.non_admix_individuals.id_group_map.txt')

batch = 'pear_July2023'


gatk_filtered_vcf_dir = os.path.join(os.path.dirname(work_dir),'run_GATK_variant_calling','output','s05.hard_filter_chr_vcf.'+batch)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)



# Read chromosomes ID list of the reference genome
with open(chromosomes,'r') as file:
    chromosome = file.read().strip().format(input_dir=input_dir).split()


# Read individuals group map
group_individual = {}
with open(individual_group_map,'r') as file:
    lines = file.readlines()
    for line in lines:
        sp, group = line.strip().split('\t')[0:2]
        group_individual[group] = group_individual.get(group,list())
        group_individual[group].append(sp)




# Set the shebang and slurm options
shebang = f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version} on {datetime.datetime.now()}
'''

sbatch_options = '''
#SBATCH -J {chr_base}.{script_basename}
#SBATCH -o {sub_script_basename}.%J.out
#SBATCH -e {sub_script_basename}.%J.err
#SBATCH -c 4
#SBATCH --mem=10G
'''

run_bcftools = '''
source {script_path}/s00.load_software 

bcftools view \\
    {vcf} \\
    -s {chosen_samples} \\
| bcftools filter \\
    -e 'AC==0 || AN==AC' \\
    -O z4 \\
    -o {nonadmix_vcf} \\

tabix {nonadmix_vcf} && \\
bcftools view -H {nonadmix_vcf} \\
| wc -l > {nonadmix_vcf}.num.txt


bcftools filter \\
    {nonadmix_vcf} \\
    -e 'MAF<0.01' \\
    -O v \\
    -o {maf_vcf} \\

tabix {maf_vcf} && \\
bcftools view -H {maf_vcf} \\
| wc -l > {maf_vcf}.num.txt
'''


# Create a shell script for each chromosome
for group_name in group_individual.keys():
    chosen_samples = ','.join(list(group_individual[group_name]))

    for chr in chromosome:
        chr_base = os.path.splitext(os.path.basename(chr))[0]

        if chr_base == 'scaffolds':
            warnings.warn(f'Chromosome {chr_base} is skipping...')
            continue
        in_vcf = os.path.join(gatk_filtered_vcf_dir,f'{batch}.{chr_base}.filtered_pixy_variant.vcf.gz')
        nonadmix_vcf = os.path.join(output_dir,f'{batch}.{chr_base}.filtered_pixy_variant.{group_name}.non_admix.vcf.gz')
        maf_vcf = os.path.join(output_dir,f'{batch}.{chr_base}.filtered_pixy_variant.{group_name}.non_admix.maf001.vcf')
        sub_script_basename = f'{script_basename}.{chr_base}.{group_name}'

        with open(os.path.join(sub_script_dir, sub_script_basename+'.sh'),'w') as fo:
            fo.write(f'{shebang}\n\n')
            fo.write(sbatch_options.format(chr_base=chr_base,script_basename=script_basename,sub_script_basename=sub_script_basename))
            fo.write(run_bcftools.format(script_path=script_path,vcf=in_vcf,input_dir=input_dir,nonadmix_vcf=nonadmix_vcf,maf_vcf=maf_vcf,chosen_samples=chosen_samples))



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))