bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir, 'input')
output_dir = os.path.join(work_dir, 'output', script_basename)
sub_script_dir = os.path.join(bin_dir, script_basename)

id_pop_file = os.path.join(input_dir, individual_pop_map_filename)
chr_list_file = os.path.join(input_dir, chromosomes_list_filename)
karyotype_file = os.path.join(input_dir, karyotype_filename )
sweed_output_dir = os.path.join(os.path.dirname(work_dir), sweed_output_dir)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)


# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Default grid size
# grids_windows = ['1000', '2000', '3000', '4000', '5000',
#                  '6000', '7000', '8000', '9000', '10000']
grids_windows = ['1000']
windows = '50'

# Read grid file
def read_grid_file(chr, grid_file):
    dic = {}
    with open(grid_file, 'r') as file:
        dic = {line.split()[0]: line.split()[1] for line in file.readlines()}
    return dic[chr]


# Read pop id file
pop_id = {}
with open(id_pop_file, 'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            id, pop = line.split()[0:2]
            pop_id[pop] = pop_id.get(pop, [])
            pop_id[pop].append(id)


# Read chr list and length
chr_list = {}
with open(karyotype_file, 'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            chr, length = line.split()[0:2]
            chr_list[chr] = length


# Function to generate RAiSD command
def generate_RAiSD_command(run_name, chr_length, snp_num, grid_parameter):
    global work_dir, output_dir, bin_dir, sub_script_dir, script_basename, version, start_time, vcf_prefix
    sub_script_prefix = f's02.run_RAiSD.{run_name}'
    with open(os.path.join(sub_script_dir, f'{sub_script_prefix}.sh'), 'w') as file:
        file.write(
            f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version}, at {start_time:%Y-%m-%d %H:%M:%S}
#SBATCH -J {sub_script_prefix}
#SBATCH -o {sub_script_prefix}.%J.out
#SBATCH -e {sub_script_prefix}.%J.err
#SBATCH -c 1
#SBATCH --mem=3G

# Set up environment
source {bin_dir}/s00.load_RAiSD.sh

# Run RAiSD
RAiSD -n {run_name} \\
      -I {vcf_prefix}.vcf \\
      -B {chr_length} {snp_num} \\
      {grid_parameter} \\
      -R \\
      -f \\
      -k 0.05 \\
      -s \\
      -t \\
      -P \\
      -A 0.995


mv RAiSD_*.{run_name}* {output_dir}

# mv RSDPlot_*.R {output_dir}
    # -P
    # -A 0.995
''')


for pop, ids in pop_id.items():
    for chr, chr_length in chr_list.items():
        grid_methods = ['by_grid', 'by_win', 'no_grid']
        vcf_prefix = os.path.join(
                work_dir, 'output', 's01.get_vcf_by_pop_from_variant', f'{batch}.{chr}.{pop}')
        snp_num = open(vcf_prefix+'.vcf.num.txt', 'r').read().strip()
        run_name_prefix = f'{pop}.{chr}'
        for grid_method in grid_methods:
            if grid_method == 'no_grid':
                continue
                # grid_parameter = ''
                # run_name = f'{run_name_prefix}.{grid_method}'
                # generate_RAiSD_command(
                #     run_name, chr_length, snp_num, grid_parameter
                #     )

            elif grid_method == 'by_win':
                continue
                # grid_parameter = f'-w {windows}'
                # run_name = f'{run_name_prefix}.{grid_method}{windows}'
                # generate_RAiSD_command(
                #     run_name, chr_length, snp_num, grid_parameter
                #     )

            elif grid_method == 'by_grid':
                for grid_window in grids_windows:
                    grid_num = read_grid_file(chr, os.path.join(
                        input_dir, f'grid_chr.{grid_window}.txt'))
                    run_name = f'{run_name_prefix}.{grid_method}{grid_window}'
                    sweed_file_name = f'SweeD_Report.{pop}.{chr}.grid{grid_window}'
                    sweed_file = os.path.join(sweed_output_dir, sweed_file_name)

                    if not os.path.exists(sweed_file):
                        print(f'{sweed_file} not exists, skip.')
                        grid_parameter = f'-G {grid_num}'
                    else:
                        sweed_result = open(sweed_file, 'r').read().strip().split('\n')
                        if sweed_result[0].strip() == '//1' \
                            and sweed_result[1].strip().startswith('Position'):
                            sweed_result = sweed_result[2:]
                        sweed_file_no_header = os.path.join(output_dir, f'{sweed_file_name}')
                        with open(sweed_file_no_header, 'w') as file:
                            file.write('\n'.join(sweed_result)+'\n')

                        grid_parameter = f'''-G {grid_num} \\
      -CO {sweed_file_no_header} 1 2 \\
      -COT 0.05 \\
      -COD 2'''

                    generate_RAiSD_command(
                        run_name, chr_length, snp_num, grid_parameter)


