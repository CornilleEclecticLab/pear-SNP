import datetime
import sys
import textwrap
import os
import random
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

batch = 'pear_July2023'

grids = ['1000','2000','3000','4000','5000','6000','7000','8000','9000','10000']

id_group_file = os.path.join(input_dir,'s02.non_admix_individuals.id_group_map.txt')

chr_list_file = os.path.join(input_dir,'s02.chr_list.txt')



# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)



group_id = {}
with open(id_group_file,'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            id,group = line.split()[0:2]
            group_id[group] = group_id.get(group,[])
            group_id[group].append(id)



chr_list = []
with open(chr_list_file,'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            chr_list.append(line)



for groups, ids in group_id.items():
    for chr in chr_list:
        for grid in grids:
            sub_script_prefix = f's02.run_RAiSD.{groups}.{chr}.grid{str(grid)}'
            vcf_prefix = os.path.join(input_dir,'vcf',f'{batch}.{chr}.filtered_pixy_variant.{group}.nonadmix.maf001')
            with open(os.path.join(sub_script_dir,sub_script_prefix+'.sh'),'w') as file:
                file.write(
                    f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version}, at {start_time:%Y-%m-%d %H:%M:%S}
#SBATCH -J {sub_script_prefix}
#SBATCH -o {sub_script_prefix}.out
#SBATCH -e {sub_script_prefix}.err
#SBATCH -c 1

# Set up environment
source {bin_dir}/s00.load_RAiSD.sh


# Run RAiSD
RAiSD \\
    -n {sub_script_prefix}.grid \\
    -I {vcf_prefix}.vcf \\
    -G {grid} \\
    -R \\
    -f \\
    -k 0.05 \\
    -P


RAiSD \\
    -n {sub_script_prefix}.win50 \\
    -I {vcf_prefix}.vcf \\
    -w 50 \\
    -R \\
    -f \\
    -k 0.05 \\
    -P
    # -M 3 # 
    # -y 2 #

mv RAiSD_*.{sub_script_prefix}* {output_dir} 
''')




end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))