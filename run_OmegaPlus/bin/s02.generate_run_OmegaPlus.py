import datetime
import sys
import textwrap
import os
import random
from s00_config import batch, individual_pop_map_filename, chromosomes_list_filename



start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.1.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)

id_pop_file = os.path.join(input_dir, individual_pop_map_filename)

chr_list_file = os.path.join(input_dir, chromosomes_list_filename)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


grids_windows = ['1000', '2000', '3000', '4000', '5000',
         '6000', '7000', '8000', '9000', '10000']

def read_grid_file(chr, grid_file):
    dic = {}
    with open(grid_file,'r') as file:
        dic = {line.split()[0]: line.split()[1] for line in file.readlines()}
    return dic[chr]


pop_id = {}
with open(id_pop_file,'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            id,pop = line.split()[0:2]
            pop_id[pop] = pop_id.get(pop,[])
            pop_id[pop].append(id)


chr_list = []
with open(chr_list_file,'r') as file:
    for line in file:
        line = line.strip()
        if line.startswith('#'):
            continue
        else:
            chr_list.append(line)


for pop, ids in pop_id.items():
    for chr in chr_list:
        for grid_window in grids_windows:
            grid_num = read_grid_file(chr, os.path.join(
                input_dir, f'grid_chr.{grid_window}.txt'))
            sub_script_prefix = f's02.run_OmegaPlus.{pop}.{chr}.grid{str(grid_window)}'
            vcf_prefix = os.path.join(output_dir,'s01.get_vcf_by_pop',f'{batch}.{chr}.{pop}')
            random_seed = random.randint(100000, 999999)
            with open(os.path.join(sub_script_dir,sub_script_prefix+'.sh'),'w') as file:
                file.write(
                    f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version}, at {start_time:%Y-%m-%d %H:%M:%S}
#SBATCH -J {sub_script_prefix}
#SBATCH -o {sub_script_prefix}.%J.out
#SBATCH -e {sub_script_prefix}.%J.err
#SBATCH -c 4

# Set up environment
source {bin_dir}/s00.load_OmegaPlus.sh


# Run OmegaPlus
OmegaPlus-M \\
    -name {sub_script_prefix}.min5K.max100K \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num} \\
    -minwin 5000 \\
    -maxwin 100000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed} 


OmegaPlus-M \\
    -name {sub_script_prefix}.min2500 \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num} \\
    -minwin 2500 \\
    -maxwin 10000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed} 


OmegaPlus-M \\
    -name {sub_script_prefix}.min1000 \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num} \\
    -minwin 1000 \\
    -maxwin 10000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed} 

OmegaPlus-M \\
    -name {sub_script_prefix}.min2000 \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num} \\
    -minwin 2000 \\
    -maxwin 10000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed} 

OmegaPlus-M \\
    -name {sub_script_prefix}.min4000 \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num} \\
    -minwin 4000 \\
    -maxwin 10000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed}

OmegaPlus-M \\
    -name {sub_script_prefix}.min5000 \\
    -input {vcf_prefix}.vcf \\
    -grid {grid_num}\\
    -minwin 5000 \\
    -maxwin 10000 \\
    -all \\
    -minsnps 5 \\
    -threads 4 \\
    -seed {random_seed}

mv OmegaPlus_*.{sub_script_prefix}.min* {output_dir} 
''')




end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))