import datetime
import sys
import textwrap
import os
from s00_config import batch, input_merged_vcf_path, individual_pop_map_filename, chromosomes_list_filename

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)
chromosomes_list_path = os.path.join(input_dir, chromosomes_list_filename)
load_bcftools = os.path.join(bin_dir, 's00.load_bcftools.sh')


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)



# gatk_filtered_vcf_dir = os.path.join(os.path.dirname(
#     work_dir), 'run_GATK_variant_calling', 'output', 's05.hard_filter_chr_vcf.'+batch)


# Read chromosomes ID list of the reference genome
chromosomes_list_path = os.path.join(input_dir, chromosomes_list_filename)
with open(chromosomes_list_path, 'r') as file:
    chromosomes = file.read().strip().format(input_dir=input_dir).split()

# Read individuals pop map
individual_pop_map = os.path.join(
    input_dir, individual_pop_map_filename)
pop_individual = {}
with open(individual_pop_map, 'r') as file:
    lines = file.readlines()
    for line in lines:
        id, pop = line.strip().split()[0:2]
        pop_individual[pop] = pop_individual.get(pop, [])
        pop_individual[pop].append(id)

# Set the shebang and slurm options
shebang = f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version} on {datetime.datetime.now()}
'''
sbatch_options = '''
#SBATCH -J {chr_base}.{script_basename}
#SBATCH -o {sub_script_basename}.%J.out
#SBATCH -e {sub_script_basename}.%J.err
#SBATCH -c 4
#SBATCH --mem=10G
'''

run_bcftools = '''


bcftools view \\
    {vcf} \\
    -s {chosen_samples} \\
    -r {chr_base} \\
| bcftools filter \\
    -e 'AC==0 || AN==AC' \\
    -O v \\
    -o {nonadmix_vcf}

tabix {nonadmix_vcf} && \\
bcftools view -H {nonadmix_vcf} \\
| wc -l > {nonadmix_vcf}.num.txt


bcftools filter \\
    {nonadmix_vcf} \\
    -e 'MAF<0.01' \\
    -O v \\
    -o {maf_vcf}

tabix {maf_vcf} && \\
bcftools view -H {maf_vcf} \\
| wc -l > {maf_vcf}.num.txt
'''


# Create a shell script for each chromosome
for pop_name, ids in pop_individual.items():
    chosen_samples = ','.join(ids)

    for chr in chromosomes:
        chr_base = os.path.splitext(os.path.basename(chr))[0]
        if chr_base == 'scaffolds':   # For compatibility with the original chr_list.txt
            warnings.warn(f'Chromosome {chr_base} is skipping...')
            continue

        nonadmix_vcf = os.path.join(
            output_dir, f'{batch}.{chr_base}.{pop_name}.vcf')
        maf_vcf = os.path.join(
            output_dir, f'{batch}.{chr_base}.{pop_name}.maf001.vcf')
        sub_script_basename = f'{script_basename}.{chr_base}.{pop_name}'

        with open(os.path.join(sub_script_dir, sub_script_basename+'.sh'), 'w') as fo:
            fo.write(f'{shebang}\n\n')
            fo.write(sbatch_options.format(chr_base=chr_base,
                                           script_basename=script_basename, sub_script_basename=sub_script_basename)
                     )
            fo.write(run_bcftools.format(script_path=script_path,
                                         vcf=input_merged_vcf_path,
                                         input_dir=input_dir,
                                         nonadmix_vcf=nonadmix_vcf,
                                         maf_vcf=maf_vcf,
                                         chosen_samples=chosen_samples,
                                         chr_base=chr_base,
                                         load_bcftools=load_bcftools)
                     )


end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time-start_time).center(79))
