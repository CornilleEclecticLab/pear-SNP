import datetime
import sys
import textwrap
import os
import glob
from s00_config import *
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir, 'input')
output_dir = os.path.join(work_dir, 'output')
sub_output_dir = os.path.join(output_dir, script_basename)
sub_script_dir = os.path.join(bin_dir, script_basename)

# Ensure output directory exists
os.makedirs(sub_output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Collect populations from the folders of s06
populations = map(os.path.basename,  
                  glob.glob(os.path.join(output_dir, s06_dir, '*')))
populations = list(populations)

# Laod sample population file
sample_population = {}
with open(os.path.join(input_dir, sample_population_txt)) as f:
    for line in f:
        sample, pop = line.strip().split()
        sample_population[pop] = sample_population.get(pop, [])
        sample_population[pop].append(sample)


# Load ChrID-number file
chrID_number = {}
with open(os.path.join(input_dir, chrID_number_txt)) as f:
    for line in f:
        chr, number = line.strip().split()
        chrID_number[chr] = number

shebang = '#!/usr/bin/bash'
shebaangR = '#!/usr/bin/env Rscript'
header = f"""
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""
for pop in populations:
    if pop not in sample_population:
        print(
            wrap79(f'Skip population {pop} that not found in {sample_population_txt}'))
        continue
    os.makedirs(os.path.join(sub_output_dir, pop), exist_ok=True)
    
    fasteprr_results = glob.glob(os.path.join(output_dir, s06_dir, pop, 'FastEPRR_step4.*.txt'))
    for file in fasteprr_results:
        base_name = os.path.basename(file)
        prefix = os.path.splitext(base_name)[0]
        splits = prefix.split('.')
        chr = splits[2]
        with open(os.path.join(sub_output_dir, pop, prefix+'.withChr.bed'), 'w') as fo:
            with open(file) as fi:
                for line in fi:
                    line_with_tabs = line.replace(" ", "\t")
                    if line.startswith('Start'):
                        fo.write("#Chr\t"+line_with_tabs)
                        pass
                    else:
                        bed_line = str(int(line.split()[0]) - 1) + '\t' + '\t'.join(line.split()[1:])
                        fo.write(f'{chr}\t{bed_line}\n')
        
        sub_script_base = script_basename + f'.{pop}.{chr}'
        with open(os.path.join(sub_script_dir, sub_script_base+'.sh'), 'w') as fo:
            fo.write(f"""{shebang}
{header}

#SBATCH -J {sub_script_base}.sh
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH -c 1
#SBATCH --mem=1G

source {bin_dir}/s00.load_bedtools.sh

bedtools intersect \\
    -a {os.path.join(sub_output_dir, pop, prefix+'.withChr.bed')} \\
    -b {os.path.join(input_dir, f'{chr}.pass.bed')} \\
    -wa \\
    > {os.path.join(sub_output_dir, pop, prefix+'.masked.txt')}
""")



end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time-start_time).center(79))
