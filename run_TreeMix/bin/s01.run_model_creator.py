import datetime
import sys
import textwrap
import os
import subprocess
import argparse

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


# Set the parameters for treemix
argparser = argparse.ArgumentParser(description='Create scripts to run TreeMix')
argparser.add_argument('-m','--m-max', type=int, default=5, help='Maximum migration events')
argparser.add_argument('-c','--repeat', type=int, default=10, help='Number of times to recycle the data')
argparser.add_argument('-r','--root', type=str, required=True, help='Root population')
argparser.add_argument('-v','--vcf', type=str, default='../input/s01.input.vcf.gz', help='Input VCF file')
argparser.add_argument('-p','--population', type=str, required= True, help='Input population file, format: sample tab population')
args = argparser.parse_args()

m_max = args.m_max      # Maximum migration events
repeat = args.repeat    # Number of times to recycle the data
root = args.root        # Root population
print(f'root: {root}')


# Set the global variables
version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir, 'input')
output_dir = os.path.join(work_dir, 'output')
sub_output_dir = os.path.join(output_dir, script_basename)
sub_script_dir = os.path.join(bin_dir, script_basename)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)


# Read the sample_tab_population file
sample_tab_population = args.population  # os.path.join(input_dir,'s01.sample_tab_population.txt')
population_dict = {}
with open(sample_tab_population, 'r', encoding='utf-8') as f:
    for line in f:
        line = line.strip()
        if line.startswith('#'):
            continue
        ind, pop = line.split()
        population_dict[pop] = population_dict.get(pop, [])
        population_dict[pop].append(ind)

if root not in population_dict:
    print(wrap79(
        f'Error: root population {root} not found in {sample_tab_population}'))
    sys.exit(1)

# Set the model name
population_list = list(population_dict.keys())
population_num = len(population_list)
model_name = f'{population_num}Pops_{root}'
print(f'Model name: {model_name}')
population_list_filename = f'{model_name}.txt'
population_list_filepath = os.path.join(
    sub_output_dir, population_list_filename)

# Set the output directories
s02_sub_output_dir = os.path.join(output_dir, 's02.treemix.' + model_name)
s03_sub_output_dir = os.path.join(output_dir, 's03.plot.' + model_name)
s04_sub_output_dir = os.path.join(output_dir, 's04.bootstraps.' + model_name)
s04_sub_bin_dir = os.path.join(bin_dir, 's04.bootstraps.' + model_name)

# Ensure output directory exists
os.makedirs(sub_output_dir, exist_ok=True)
os.makedirs(s02_sub_output_dir, exist_ok=True)
os.makedirs(s03_sub_output_dir, exist_ok=True)
os.makedirs(s04_sub_output_dir, exist_ok=True)
os.makedirs(s04_sub_bin_dir, exist_ok=True)


# Write the population list to a file
with open(population_list_filepath, 'w', encoding='utf-8') as f:
    f.write('\n'.join(population_list))

# Write the individual list for each population to a file
for pop, ind_list in population_dict.items():
    with open(os.path.join(sub_output_dir, f'{pop}.txt'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(ind_list))

# Set the parameters for model_creator.py
pop_ind_file_tag = ' \\\n    '.join(['--pop-ind-file ' + pop + ' ' + str(os.path.join(sub_output_dir, f'{pop}.txt')) for pop in population_list])
model_file = os.path.join(sub_output_dir, f'{model_name}.model')
treemix_file_prefix = os.path.join(sub_output_dir, f'{model_name}_treemix')

# Run model_creator.py
subprocess.run(f'''
#!/bin/bash
source s00.load_py-popgen.sh
source s00.load_bcftools.sh

model_creator.py \\
    --model {model_name} \\
    --model-pop-file {model_name} {population_list_filepath} \\
    {pop_ind_file_tag} 

mv out.model {model_file}

# Convert the VCF file to TreeMix format
vcf_to_treemix.py \\
    --vcf {args.vcf} \\
    --model-file {model_file} \\
    --modelname {model_name} \\
    --out {treemix_file_prefix}
''', shell=True, executable='/bin/bash', check=True)


# Treemix file name
treemix_output_file_prefix = f'{model_name}_treemix'
treemix_output_prefix = os.path.join(s02_sub_output_dir, treemix_output_file_prefix)

# Write a SLURM script to run TreeMix
header = f"""#!/usr/bin/env bash
# This script was generated by {script_basename}.py
# at {start_time}
# v{version}
"""

sub_script_base = 's02.run_treemix.' + model_name
sub_script_path = os.path.join(bin_dir, sub_script_base + '.sh')
with open(sub_script_path, 'w', encoding='utf-8') as fo:
    fo.write(header)
    fo.write(f"""
#SBATCH -J {sub_script_base}
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH --array=0-{m_max}
#SBATCH -c 4
#SBATCH --mem=8G
#SBATCH -p long

source s00.load_treemix.sh

m=$SLURM_ARRAY_TASK_ID

treemix \\
    -i {treemix_file_prefix}.gz \\
    -o {treemix_output_prefix}_mig_${{m}} \\
    -m ${{m}} \\
    -noss \\
    -global \\
    -k 500 \\
    -root {root}
""")

# Write R script to plot
header_r = f"""
plotting_funcs_path <- readLines('s00.path_to_plotting_funcs_R.txt')
source(plotting_funcs_path)
"""

sub_script_base = 's03.plot_treemix.' + model_name
sub_script_path_r = os.path.join(bin_dir, sub_script_base + '.R')
with open(sub_script_path_r, 'w', encoding='utf-8') as fo:
    fo.write(header)
    fo.write(header_r)
    for m in range(m_max + 1):
        fo.write(f"""
pdf(file = "{s03_sub_output_dir}/{treemix_output_file_prefix}_mig_{m}.pdf",
    width = 10, # The width of the plot in inches
    height = 4) # The height of the plot in inches
plot_tree("{treemix_output_prefix}_mig_{m}")
dev.off()
""")

# Write SLURM scripts to run Bootstraps
treemix_bootstrap_output_prefix = os.path.join(s04_sub_output_dir, treemix_output_file_prefix)

for m in range(m_max + 1):
    sub_script_base = f's04.run_TreeMix_Bootstraps.{model_name}.m{m}'
    sub_script_path_bootstrap = os.path.join(s04_sub_bin_dir, sub_script_base + '.sh')
    with open(sub_script_path_bootstrap, 'w', encoding='utf-8') as fo:
        fo.write(header)
        fo.write(f"""
#SBATCH -J {sub_script_base}
#SBATCH -o {sub_script_base}.%J.out
#SBATCH -e {sub_script_base}.%J.err
#SBATCH --array=0-{repeat}
#SBATCH -c 4
#SBATCH --mem=8G
#SBATCH -p long

source {os.path.join(bin_dir, 's00.load_treemix.sh')}

i=$SLURM_ARRAY_TASK_ID
m={m}

treemix \\
    -i {treemix_file_prefix}.gz \\
    -o {treemix_bootstrap_output_prefix}.${{i}}.{m} \\
    -bootstrap \\
    -m {m} \\
    -noss \\
    -global \\
    -k 500 \\
    -seed ${{s}}
""")

end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time - start_time).center(79))