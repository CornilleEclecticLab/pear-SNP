import datetime
import warnings,os

start_time = datetime.datetime.now()
print("{0:=^40}".format(' Start '))


work_dir       = '/data/atipe-workspace/ynie/pear/run_QC'
input_dir      = work_dir+"/input"
output_dir     = work_dir+"/output"
s03_dir        = work_dir+"/bin/s03.fastp_and_qc"
s03_prefix     = "s03.fastp_and_qc"
s03_output_dir = output_dir+"/"+s03_prefix


dic={}

with open(input_dir+"/fastp_cutoff.dic.txt",'r') as fo:
    for line in fo:
        line = line.strip()
        
        if line.startswith("#"):
            continue
        
        line = line.split()
        
        if len(line)!=6:
            print(len(line))
            warnings.warn("WARNING: bad input file\
                , this record is not 6 columns: "+' '.join(line))
        
        path = line[0]
        file_prefix = line[1]
        sample=os.path.basename(os.path.dirname(path))
        project = line[2]
        front_trimmin = line[3]
        length_require = line[4]
        average_length = line[5]
        dic[sample]=dic.get(sample,[])
        dic[sample].append(line)
        
        
os.system("mkdir -p "+s03_dir)
os.system("mkdir -p "+s03_output_dir)

content_header='''#!/usr/bin/env bash
# bash file generated by ../s03.fastp_and_qc.py
'''

for sample,value in dic.items():
    if len(value) != 2:
        print(sample, len(value))
        warnings.warn("WARNING: this sample contains only ONE fastq file, as you had checked it, it would be discard for fastp running: "+value[0][0])
        continue
    
    if value[0][2] != value[1][2] or value[0][3] != value[1][3] or value[0][4] != value[1][4]:
        warnings.warn("WARNING: Bad record in the input file, as the paired fastq files with different parameters: "+str(value))
    
    with open(s03_dir+'/'+s03_prefix+"_"+sample+".sh",'w') as fo:
        fo.write(content_header)
        content='''

mkdir -p {dir}


fastp \\
-f {f} \\
-l {l} \\
-i {i} \\
-I {I} \\
-o {o} \\
-O {O} \\
-h {h} \\
-j {j} \\
-R {R} &&


fastqc \\
-t 2 \\
-f fastq \\
-o {oqc} \\
{o} &&


fastqc \\
-t 2 \\
-f fastq \\
-o {OQC} \\
{O}

'''.format(
f=value[0][3], \
l=value[0][4], \
i=value[0][0], \
I=value[1][0], \
dir=s03_output_dir+"/"+value[0][2]+"/"+sample, \
o=s03_output_dir+"/"+value[0][2]+"/"+sample+"/clean."+os.path.basename(value[0][0]), \
O=s03_output_dir+"/"+value[1][2]+"/"+sample+"/clean."+os.path.basename(value[1][0]), \
h=s03_output_dir+"/"+value[0][2]+"/"+sample+"/fastp."+sample+".html", \
j=s03_output_dir+"/"+value[0][2]+"/"+sample+"/fastp."+sample+".json", \
R=sample, \
oqc=s03_output_dir+"/"+value[1][2]+"/"+sample, \
OQC=s03_output_dir+"/"+value[1][2]+"/"+sample)
        
        fo.write(content)


end_time = datetime.datetime.now()
print('')
print(' END '.center(40,'='))
print(str(end_time-start_time).center(40))
