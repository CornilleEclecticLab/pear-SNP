import datetime
import os
import warnings

start_time = datetime.datetime.now()
print("{0:=^40}".format(' Start '))


work_dir = '/data/atipe-workspace/ynie/pear/run_QC'
input_dir = work_dir+"/input"
output_dir = work_dir+"/output"
s03_dir = work_dir+"/bin/s03.fastp_and_qc"
s03_prefix = "s03.fastp_and_qc"
s03_output_dir = output_dir+"/"+s03_prefix


dic={}

with open(input_dir+"/fastp_cutoff.dic.txt", 'r') as fo:
    for line in fo:
        line = line.strip()

        if line.startswith("#"):
            continue

        line = line.split()

        if len(line) != 6:
            print(len(line))
            warnings.warn("WARNING: bad input file, this record is not 6 columns: "+' '.join(line))

        path = line[0]

        # Check the file path
        if os.path.splitext(path)[1] != ".gz":
            warnings.warn("WARNING: bad input file\
                , this record is not a fastq.gz file: "+path)
            continue

        if os.path.splitext(os.path.splitext(path)[0])[1] not in [".fastq", ".fq"]:
            warnings.warn("WARNING: bad input file\
                , this record is not a fastq.gz file: "+path)
            continue

        file_prefix = line[1]
        sample = os.path.basename(os.path.dirname(path))

        # The expected input file content:
        # project = line[2]
        # front_trim_min = line[3]
        # length_require = line[4]
        # average_length = line[5]
        dic[sample] = dic.get(sample, [])
        dic[sample].append(line)


os.system("mkdir -p "+s03_dir)
os.system("mkdir -p "+s03_output_dir)

content_header=f'''#!/usr/bin/env bash
# bash file generated by ../s03.fastp_and_qc.py at {start_time}
'''



for sample, value in dic.items():
    # Check the fastq file number
    if len(value)%2 == 1:
        print(sample, len(value), "fastq files")
        warnings.warn(
            "WARNING: the sample "+sample+" contains NON-Pair fastq file, please checked it, it would be discard for fastp running: "+value[0][0])
        continue

    elif len(value) > 2:
        print("the sample "+sample+" contains ("+str(len(value))+") more than two fastq files")

    fastq1s, fastq2s = [], []
    for m in range(len(value)):
        # Check the fastq file name
        fq_file_path = value[m][0] # *.fastq.gz
        fq_file_split = os.path.splitext(fq_file_path)
        fq_prefix, fq_suffix = fq_file_split[0],fq_file_split[1] # *.fastq,  .gz
        fq_prefix_split = os.path.splitext(fq_prefix)
        prefix2 ,suffix2 = fq_prefix_split[0], fq_prefix_split[1] #  *_1 , .fastq OR # 1.clean, fastq

        if prefix2.endswith("1") or prefix2.endswith("1.clean"):
            fastq1s.append(m)
        elif prefix2.endswith("2") or prefix2.endswith("2.clean"):
            fastq2s.append(m)
        else:
            warnings.warn(
                "WARNING: Unrecognized record of file name in the input file: "+str(value))

        # Check the fastq file parameters consistency
        for i in [2, 3, 4]:
            if value[m][i] != value[0][i]:
                warnings.warn(
                    "WARNING: Bad record in the input file, as the paired fastq files with different parameters: "+str(value))

    # Check the fastq file number
    if len(fastq1s) != len(fastq2s) or len(fastq1s) + len(fastq2s) != len(value):
        warnings.warn(
            "WARNING: Unequal number of fastq files: "+str(value))
        continue

    fastq1=fastq1s[0]
    fastq2=fastq2s[0]

    if len(value) == 2:
        fq1_input = value[fastq1][0]
        fq2_input = value[fastq2][0]
        content_merge_fastq = ''

    elif len(value) > 2:
        fq1_inputs = ' '.join([value[m][0] for m in fastq1s])
        fq1_input = s03_output_dir+"/"+value[fastq1][2]+"/"+sample+"/raw.merged."+value[fastq1][1]
        fq2_inputs = ' '.join([value[m][0] for m in fastq2s])
        fq2_input = s03_output_dir+"/"+value[fastq2][2]+"/"+sample+"/raw.merged."+value[fastq2][1]
        content_merge_fastq = f'''
zcat {fq1_inputs} | bgzip -c --threads 2 > {fq1_input} 

zcat {fq2_inputs} | bgzip -c --threads 2 > {fq2_input} 

'''

    with open(s03_dir+'/'+s03_prefix+"_"+sample+".sh", 'w') as fo:
        fo.write(content_header)
        content = '''

mkdir -p {dir}

{content_merge_fastq}

fastp \\
-f {f} \\
-l {l} \\
-i {i} \\
-I {I} \\
-o {o} \\
-O {O} \\
-h {h} \\
-j {j} \\
-R {R} 


fastqc \\
-t 2 \\
-f fastq \\
-o {oqc} \\
{o}


fastqc \\
-t 2 \\
-f fastq \\
-o {OQC} \\
{O}

'''.format(
            f=value[fastq1][3],
            l=value[fastq1][4],
            i=fq1_input,
            I=fq2_input,
            dir=s03_output_dir+"/"+value[fastq1][2]+"/"+sample,
            content_merge_fastq=content_merge_fastq,
            o=s03_output_dir+"/"+value[fastq1][2]+"/"+sample + # Version 2.0.0 2023-09-13 11:27:19
                "/clean."+value[fastq1][1],                    # Version 2.0.0 2023-09-13 11:27:19
            O=s03_output_dir+"/"+value[fastq2][2]+"/"+sample + # Version 2.0.0 2023-09-13 11:27:19
                "/clean."+value[fastq2][1],                    # Version 2.0.0 2023-09-13 11:27:19
            # Version 1.0.0
            # o=s03_output_dir+"/"+value[fastq1][2]+"/"+sample +
            #     "/clean."+os.path.basename(value[fastq1][0]),
            # O=s03_output_dir+"/"+value[fastq2][2]+"/"+sample +
            #     "/clean."+os.path.basename(value[fastq2][0]),
            h=s03_output_dir+"/"+value[fastq1][2] +
                "/"+sample+"/fastp."+sample+".html",
            j=s03_output_dir+"/"+value[fastq1][2] +
                "/"+sample+"/fastp."+sample+".json",
            R=sample,
            oqc=s03_output_dir+"/"+value[fastq1][2]+"/"+sample,
            OQC=s03_output_dir+"/"+value[fastq2][2]+"/"+sample)

        fo.write(content)


end_time = datetime.datetime.now()
print('')
print(' END '.center(40,'='))
print(str(end_time-start_time).center(40))
