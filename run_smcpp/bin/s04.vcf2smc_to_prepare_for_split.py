import datetime
import os
import sys
import textwrap
from warnings import warn
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.2"
script_basename = "s04.vcf2smc_to_prepare_for_split"
s05_script = 's05.split_time_estimation.py'
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
work_dir = os.path.dirname(script_path)
input_dir = work_dir+'/input/'
output_dir = work_dir+'/output/'+script_basename
sub_script_dir = work_dir+'/bin/'+script_basename



vcf = input_dir+"/s01.input.vcf.gz"
mask = '/shared/ifbstor1/projects/pear_snp3/pear/run_genmap_Genome_Mappability/output/GWHBAOS00000000.genome.genmap.mask.bed'
chromosome_list = input_dir+"/s01.scaffolds_list.txt"  
individual_population_list = input_dir+"/s01.individuals_and_populations_list.txt" # Format: individual_name population_name
population_pair_list = input_dir+"/s04.population_pair_list.txt" # Format: population1 population2
load_singularity = 'module load system/singularity-3.7.3'



os.system("mkdir -p "+sub_script_dir)
os.system("mkdir -p "+output_dir)



def wrap(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)



## Read the chromosome list
with open(chromosome_list,'r') as fr:
    chr_list = fr.read().strip().split('\n')
    info=f'Reading the "chromosomes list": {",".join(chr_list)}'
    print(wrap(info))



## Read the individuals and populations list
population_dict = {}
with open(individual_population_list,'r') as fr:
    for line in fr:
        if line.startswith("#") or line.strip()=='':
            continue 
        line = line.strip().split()
        individual = line[0]
        population = line[1]
        info=f'Reading the "individuals_and_populations_list": {individual} {population}'
        print(wrap(info))

        population_dict[population] = population_dict.get(population,list())
        population_dict[population].append(individual)



## Read the population pair list
if os.path.exists(population_pair_list):
    ls = list()
    with open(population_pair_list,'r') as fr:
        for line in fr:
            if line.startswith("#") or line.strip()=='':
                continue

            line = line.strip().split()
            pop1 = line[0]
            pop2 = line[1]

            if pop1 == pop2:
                warn(wrap(f'Population "{pop1}" is paired with itself.'))
                continue
            if (pop1,pop2) in ls or (pop2,pop1) in ls:
                warn(wrap(f'Population pair "{pop1} {pop2}" is duplicated.'))
                continue
            if pop1 not in population_dict.keys() or pop2 not in population_dict.keys():
                warn(wrap(f'Population "{pop1}" or "{pop2}" is not found in the "{individual_population_list}" file.'))
                exit(1)

            ls.append((pop1,pop2))
            info=f'Reading the "population_pair_list": {pop1} {pop2}'
            print(wrap(info))
    population_pair_list = ls


## Generate the population pair list
elif not os.path.exists(population_pair_list):
    info=f'Did not find the {population_pair_list} file, the script will generate the population pairs for you, or you could define the populations pairs for SMC++ with this format: \n    Population1  Population2.\n It will works in the next time you run this "{script_basename}.py" script, and it will be also used in the "{s05_script}" script.'
    print(wrap(info))

    info=f'Generating the "population_pair_list" from the "individuals_and_populations_list".'
    print(wrap(info))

    ls = list()
    for j in range(len(population_dict.keys())):
        for k in range(j+1,len(population_dict.keys())):
            pop1 = list(population_dict.keys())[j]
            pop2 = list(population_dict.keys())[k]
            # if pop1 == pop2:
            #     continue
            ls.append((pop1,pop2))
    
    with open(population_pair_list,'w') as fw:
        fw.write(f'# This file was generated by {script_basename}.py V{version} at {start_time}\n')

        for (pop1,pop2) in ls:
            fw.write(f'{pop1} {pop2}\n')
            info=f'Now the "{population_pair_list}" file is generated which has been used in this time you run this "{script_basename}.py" script, and it will be also used in the "{s05_script}" script.'
            print(wrap(info))
    population_pair_list = ls

print(wrap(f'Population pair list: {",".join([str(i) for i in population_pair_list])}'))

if len(population_pair_list) == 0:
    warn(wrap(f'No population pair was found in the "{population_pair_list}" file. If you do not want to use the "{population_pair_list}" file, you could remove it.'))
    exit(1)



def individual_list_to_string(individual_list):
    return ",".join(individual_list)



for (pop1,pop2) in population_pair_list:
    inds1 = individual_list_to_string(population_dict[pop1])
    inds2 = individual_list_to_string(population_dict[pop2])

    for chr in chr_list:
        sub_script_basename = f'vcf2smc.{pop1}.{pop2}.{chr}.pair'
        sub_script = f"{sub_script_dir}/{sub_script_basename}.sh"
        out12 = f"{output_dir}/{pop1}.{pop2}.{chr}.smc.gz"
        out21 = f"{output_dir}/{pop2}.{pop1}.{chr}.smc.gz"

        with open(sub_script,"w") as fo:
            content = f'''#!/usr/bin/env bash

# This sub-script was generated by {script_basename}.py V{version} at {start_time}


#SBATCH -J {sub_script_basename}
#SBATCH -o {sub_script_basename}.%J.out
#SBATCH -e {sub_script_basename}.%J.err


{load_singularity}


singularity run -B  {work_dir}:{work_dir} \\
    {work_dir}/bin/smcpp.sif vcf2smc \\
        --mask {mask} \\
        {vcf} \\
        {out12} \\
        {chr} \\
        {pop1}:{inds1} \\
        {pop2}:{inds2} && \\
singularity run -B  {work_dir}:{work_dir} \\
    {work_dir}/bin/smcpp.sif vcf2smc \\
        --mask {mask} \\
        {vcf} \\
        {out21} \\
        {chr} \\
        {pop2}:{inds2} \\
        {pop1}:{inds1}

'''

            fo.write(content)



end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))
