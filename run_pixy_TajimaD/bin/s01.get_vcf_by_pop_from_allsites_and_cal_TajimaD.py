import datetime
import sys
import textwrap
import os
import warnings
from s00_config import batch, individual_pop_map_filename, chromosomes_list_filename, allsite_vcf_list_filename

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')


version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'input')
output_dir = os.path.join(work_dir,'output',script_basename)
sub_script_dir = os.path.join(bin_dir,script_basename)
chromosomes_list_path = os.path.join(input_dir, chromosomes_list_filename)


# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Function to wrap text to 79 characters
def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' '*4)

# Read chromosomes ID list of the reference genome
chromosomes_list_path = os.path.join(input_dir, chromosomes_list_filename)
with open(chromosomes_list_path, 'r') as file:
    chromosomes = file.read().strip().split()

# Read individuals pop map
individual_pop_map = os.path.join(
    input_dir, individual_pop_map_filename)
pop_individual = {}
with open(individual_pop_map, 'r') as file:
    lines = file.readlines()
    for line in lines:
        id, pop = line.strip().split()[0:2]
        pop_individual[pop] = pop_individual.get(pop, [])
        pop_individual[pop].append(id)

# Read the allsite VCF list
with open(os.path.join(input_dir, allsite_vcf_list_filename), 'r') as file:
    allsite_vcf_list = [os.path.realpath(i) for i in file.read().strip().split()]

for path in allsite_vcf_list:
    basename = os.path.basename(path)
    if not basename.startswith(f'{batch}'):
        print(f'WARNING: File {basename} does not start with the batch name {batch}')
    if os.path.basename(path).split(".")[1] not in chromosomes:
        raise ValueError(f'Chromosome {os.path.basename(path).split(".")[1]} is not in the chromosomes list')

allsite_chr_vcf_dic = {os.path.basename(path).split(".")[1]: path for path in allsite_vcf_list}

# Variation vcf chr list
for chr in chromosomes:
    if chr not in allsite_chr_vcf_dic:
        print(allsite_chr_vcf_dic)
        raise ValueError(f'Chromosome {chr} is not in the allsite vcf list')
for chr in allsite_chr_vcf_dic:
    if chr not in chromosomes:
        raise ValueError(f'Chromosome {chr} is not in the chromosomes list')


# Set the shebang and slurm options
shebang = f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version} on {datetime.datetime.now()}
'''
sbatch_options = '''
#SBATCH -J {chr_base}.{script_basename}
#SBATCH -o {sub_script_basename}.%J.out
#SBATCH -e {sub_script_basename}.%J.err
#SBATCH -c 8
#SBATCH --mem=10G
'''

run_bcftools = '''
source {bin_dir}/s00.load_bcftools.sh
source {bin_dir}/s00.load_pixy2.sh

bcftools view \\
    {vcf} \\
    --threads 8 \\
    -s {chosen_samples} \\
    -R {input_dir}/{chr_base}.pass.bed \\
| bcftools filter \\
    -e 'AC==0 || AN==AC || F_MISSING>0.2' \\
    --threads 8 \\
| bcftools view \\
    -O z6 \\
    --threads 8 \\
    -o {masked_vcf}.gz

tabix -p vcf {masked_vcf}.gz

bcftools view -H {masked_vcf}.gz \\
| wc -l > {masked_vcf}.num.txt


pixy \\
    --vcf {masked_vcf}.gz \\
    --populations {individual_pop_map_filename} \\
    --window_size 10000 \\
    --stats pi watterson_theta tajima_d \\
    --output_folder {output_dir} \\
    --output_prefix Pixy.PPY.{chr_base}.10k \\
    --n_cores 8

pixy \\
    --vcf {masked_vcf}.gz \\
    --populations {individual_pop_map_filename} \\
    --window_size 1000 \\
    --stats pi watterson_theta tajima_d \\
    --output_folder {output_dir} \\
    --output_prefix Pixy.PPY.{chr_base}.1k \\
    --n_cores 8

pixy \\
    --vcf {masked_vcf}.gz \\
    --populations {individual_pop_map_filename} \\
    --window_size 100 \\
    --stats pi watterson_theta tajima_d \\
    --output_folder {output_dir} \\
    --output_prefix Pixy.PPY.{chr_base}.100bp \\
    --n_cores 8
'''


# Create a shell script for each chromosome

for chr in chromosomes:
    chr_base = os.path.splitext(os.path.basename(chr))[0]
    chosen_samples = ','.join(
        [i for pop_name in pop_individual.keys() for i in pop_individual[pop_name]]
    )

    if chr_base == 'scaffolds':   # For compatibility with the original chr_list.txt
        warnings.warn(f'Chromosome {chr_base} is skipping...')
        continue

    masked_vcf = os.path.join(
        output_dir, f'{batch}.{chr_base}.masked.vcf')
    sub_script_basename = f'{script_basename}.{chr_base}'

    with open(os.path.join(sub_script_dir, sub_script_basename+'.sh'), 'w') as fo:
        fo.write(f'{shebang}\n\n')
        fo.write(sbatch_options.format(chr_base=chr_base,
                                    script_basename=script_basename, sub_script_basename=sub_script_basename)
                )
        fo.write(run_bcftools.format(
            bin_dir=bin_dir,
            individual_pop_map_filename=os.path.join(input_dir,individual_pop_map_filename),
            output_dir=output_dir,
            script_path=script_path,
            vcf=allsite_chr_vcf_dic[chr_base],
            input_dir=input_dir,
            masked_vcf=masked_vcf,
            chosen_samples=chosen_samples,
            chr_base=chr_base)
        )


end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time-start_time).center(79))
