def individual_list_to_string(individual_list):
    individual_list= [str(i) for i in individual_list]
    return ",".join(individual_list)



def haplotype_list_to_string(haplotype_list1, haplotype_list2):
    haplotype_list1 = [str(i) for i in haplotype_list1]
    haplotype_list2 = [str(i) for i in haplotype_list2]

    pair = ''
    for m in haplotype_list1:
        for n in haplotype_list2:
            pair += ',' if pair else ''
            pair += f'{m}-{n}'

    return pair



